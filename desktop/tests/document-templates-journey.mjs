import { createRequire } from 'node:module';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import assert from 'node:assert/strict';
const engine = process.env.ZENTRA_QA_ENGINE || 'chromium';
const driver = createRequire(import.meta.url)(process.env.ZENTRA_PLAYWRIGHT_MODULE || 'playwright')[engine];
const browser = await driver.launch({ headless:true, ...(engine === 'chromium' && process.platform === 'win32' ? { channel:'msedge' } : {}) });
const folder = `.qa/document-templates-${engine}`;
await mkdir(folder, { recursive:true });
const report = [];
const sizes = process.env.ZENTRA_QA_WIDTHS ? JSON.parse(process.env.ZENTRA_QA_WIDTHS) : [[320,568],[390,844],[844,390],[1440,1000]];
try {
  for (const [width,height] of sizes) {
    const page = await browser.newPage({ viewport:{width,height}, reducedMotion:'reduce' });
    const errors=[]; page.on('pageerror', error=>errors.push(error.message));
    await page.route('**/native-design-fixture/*.pdf', async route => {
      const name = new URL(route.request().url()).pathname.split('/').at(-1);
      await route.fulfill({ contentType:'application/pdf', body:await readFile(`.qa/composition-pdfs/${name}`) });
    });
    await page.goto(`${process.env.ZENTRA_QA_ORIGIN || 'http://127.0.0.1:5271'}/tests/document-design-harness.html?tools=1`);
    const ready = () => page.locator('.design-studio__preview[aria-busy=false] .design-studio__pages img').first().waitFor({state:'attached', timeout:30000});
    const history = page.getByRole('group',{name:'Historique de la présentation'});
    const state = () => page.evaluate(()=>JSON.parse(sessionStorage.getItem('design-draft') || localStorage.getItem('design-settings') || '{}'));
    const templates = async () => (await state()).documentDesignTemplates ?? [];
    const tools = async () => { const button = page.getByRole('button',{name:'Mes réglages',exact:true}); if (await button.isVisible()) await button.click(); };
    const openLibrary = async () => {
      await tools(); await page.getByRole('button',{name:'Style',exact:true}).click();
      const details=page.locator('details.document-template-library');
      if(!await details.evaluate(el=>el.open)) await details.locator('summary').click();
      return details;
    };
    const text = value => value.map(p=>p.runs.map(r=>r.text).join('')).join('\n');
    const condition = 'Conditions du modèle : paiement à 30 jours.';
    await ready(); await page.getByLabel('Police du document',{exact:true}).selectOption('times');
    await page.getByLabel('Couleur personnalisée',{exact:true}).fill('#182b49');
    await page.getByRole('button',{name:'Textes',exact:true}).click();
    await page.getByRole('textbox',{name:'Conditions et message de fin',exact:true}).fill(condition);
    await page.getByRole('textbox',{name:'Conditions et message de fin',exact:true}).press('ControlOrMeta+a');
    await page.getByRole('button',{name:'Gras',exact:true}).click();
    await page.getByLabel('Police du passage',{exact:true}).selectOption('courier');
    let library = await openLibrary();
    await library.getByRole('button',{name:'Créer ce modèle',exact:true}).click();
    await library.getByRole('alert').filter({hasText:'Donnez un nom'}).waitFor();
    await page.waitForFunction(()=>document.querySelector('[aria-label="Nom du modèle"]')===document.activeElement);
    await page.getByLabel('Nom du modèle',{exact:true}).fill('Papier classique');
    await library.getByRole('button',{name:'Créer ce modèle',exact:true}).click();
    assert.equal((await templates()).length,1);
    assert.equal((await templates())[0].style.composition.fontFamily,'times');
    assert.equal((await templates())[0].style.composition.closing[0].runs[0].bold,true);
    await page.getByLabel('Nom du modèle',{exact:true}).fill('PAPIER CLASSIQUE');
    await library.getByRole('button',{name:'Créer ce modèle',exact:true}).click();
    await library.getByRole('alert').filter({hasText:'déjà un modèle'}).waitFor();
    assert.equal((await templates()).length,1);
    await page.getByLabel('Nom du modèle',{exact:true}).fill('');
    await page.getByLabel('Police du document',{exact:true}).selectOption('helvetica');
    assert.equal((await templates())[0].style.composition.fontFamily,'times');
    await library.getByRole('button',{name:'Renommer',exact:true}).click();
    await page.getByLabel('Nouveau nom du modèle',{exact:true}).fill('Papier de mon atelier');
    await library.getByRole('button',{name:'Valider le nom',exact:true}).click();
    assert.equal((await templates())[0].name,'Papier de mon atelier');
    await history.getByRole('button',{name:'Annuler',exact:true}).click();
    assert.equal((await templates())[0].name,'Papier classique');
    await history.getByRole('button',{name:'Rétablir',exact:true}).click();
    await page.getByRole('button',{name:'Devis',exact:true}).click();
    await page.getByRole('button',{name:'Textes',exact:true}).click();
    await page.getByRole('textbox',{name:'Conditions et message de fin',exact:true}).fill('Mes conditions de devis');
    library = await openLibrary();
    await library.getByRole('button',{name:'Appliquer aux devis',exact:true}).click();
    assert.equal((await state()).documentComposition.quotes.fontFamily,'times');
    assert.equal(text((await state()).documentComposition.quotes.closing),'Mes conditions de devis');
    await history.getByRole('button',{name:'Annuler',exact:true}).click();
    assert.equal((await state()).documentComposition.quotes.fontFamily,'helvetica');
    await library.getByRole('checkbox',{name:'Reprendre aussi les textes du modèle',exact:true}).check();
    await library.getByRole('button',{name:'Appliquer aux devis',exact:true}).click();
    assert.equal(text((await state()).documentComposition.quotes.closing),condition);
    await history.getByRole('button',{name:'Annuler',exact:true}).click();
    assert.equal(text((await state()).documentComposition.quotes.closing),'Mes conditions de devis');
    await history.getByRole('button',{name:'Rétablir',exact:true}).click();
    for(const [kind,label,apply] of [['invoices','Factures','aux factures'],['accounts','Bilan','au bilan'],['payslips','Fiches de salaire','aux fiches de salaire']]) {
      await page.getByRole('button',{name:label,exact:true}).click(); library=await openLibrary();
      await library.getByRole('button',{name:`Appliquer ${apply}`,exact:true}).click();
      assert.equal((await state()).documentComposition[kind].fontFamily,'times');
      await ready(); await page.getByRole('button',{name:'Exporter cet exemple',exact:true}).click();
      const exported=await page.evaluate(()=>JSON.parse(sessionStorage.getItem('design-export')));
      assert.equal(exported.style.composition.fontFamily,'times'); assert.equal(exported.style.accentColor,'#182b49');
    }
    await page.getByLabel('Nom du modèle',{exact:true}).fill('Salaire classique');
    await library.getByRole('button',{name:'Créer ce modèle',exact:true}).click();
    assert.equal((await templates()).length,2);
    await library.getByRole('button',{name:'Retirer ce modèle',exact:true}).click();
    assert.equal((await templates()).length,1);
    await history.getByRole('button',{name:'Annuler',exact:true}).click();
    assert.equal((await templates()).length,2);
    await page.evaluate(()=>window.dispatchEvent(new CustomEvent('design-fixture-update',{detail:{busy:true}})));
    await page.waitForFunction(()=>document.querySelector('.document-template-library fieldset')?.disabled);
    assert.equal(await library.getByRole('button',{name:'Créer ce modèle',exact:true}).isDisabled(),true);
    assert.equal(await library.getByRole('button',{name:'Retirer ce modèle',exact:true}).isDisabled(),true);
    await page.evaluate(()=>window.dispatchEvent(new CustomEvent('design-fixture-update',{detail:{busy:false}})));
    await page.waitForFunction(()=>!document.querySelector('.document-template-library fieldset')?.disabled);
    await ready(); await page.evaluate(()=>sessionStorage.setItem('design-save-fail','1'));
    await history.getByRole('button',{name:'Enregistrer',exact:true}).click();
    await page.getByText('Enregistrement momentanément indisponible.',{exact:true}).waitFor();
    assert.equal((await templates()).length,2);
    await page.evaluate(()=>sessionStorage.removeItem('design-save-fail'));
    await history.getByRole('button',{name:'Enregistrer',exact:true}).click();
    await page.getByText('Présentations enregistrées.',{exact:true}).waitFor();
    await page.reload(); await ready(); library=await openLibrary();
    assert.equal((await templates()).length,2);
    for(const kind of ['quotes','invoices','accounts','payslips']) assert.equal((await state()).documentComposition[kind].fontFamily,'times');
    await library.scrollIntoViewIfNeeded();
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1),false);
    await page.screenshot({path:`${folder}/${width}-library.png`,fullPage:true});
    await library.getByRole('button',{name:'Retirer ce modèle',exact:true}).click();
    const refreshed=(await templates()).map(t=>({...t,name:'Actualisé ailleurs'}));
    await page.evaluate(documentDesignTemplates=>window.dispatchEvent(new CustomEvent('design-fixture-update',{detail:{settings:{documentDesignTemplates}}})),refreshed);
    await page.waitForFunction(()=>document.querySelector('.document-template-library__card strong')?.textContent==='Actualisé ailleurs');
    await history.getByRole('button',{name:'Annuler',exact:true}).click();
    await page.getByText(/vos modèles ont été actualisés ailleurs/).waitFor();
    assert.deepEqual(await templates(),refreshed);
    assert.deepEqual(errors,[]);
    report.push({width,height,create:true,rename:true,allFourCategories:true,keepTextAndReplaceText:true,undoRedo:true,readOnly:true,saveRefusalPreserved:true,reload:true,concurrentRefreshPreserved:true,noOverflow:true});
    await page.close();
  }
  await writeFile(`${folder}/report.json`,JSON.stringify({engine,report},null,2)); console.log(JSON.stringify({engine,report}));
} finally { await browser.close(); }
