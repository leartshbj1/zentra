import { createRequire } from 'node:module';
import { mkdir, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.ZENTRA_PLAYWRIGHT_MODULE || 'playwright');
const browser = await chromium.launch({ headless: true, ...(process.platform === 'win32' ? { channel: 'msedge' } : {}) });
const report = [];
await mkdir('.qa/payroll-forms', { recursive: true });
const base = process.env.ZENTRA_QA_URL || 'http://127.0.0.1:5175';
const set = (page, key, value = '1') => page.evaluate(([key, value]) => sessionStorage.setItem(`qa-payroll-${key}`, value), [key, value]);
const calls = (page, key) => page.evaluate((key) => JSON.parse(sessionStorage.getItem(`qa-payroll-${key}`) || '[]'), key);
let activePage;
try {
  for (const width of [320, 390, 768, 1024, 1440]) {
    const page = activePage = await browser.newPage({ viewport: { width, height: 900 } });
    page.setDefaultTimeout(10000);
    page.on('pageerror', (error) => report.push({ error: error.stack }));
    await page.emulateMedia({ reducedMotion: 'reduce' });
    await page.goto(`${base}/tests/mobile-harness.html?payroll=1`);
    const tour = page.getByRole('button', { name: 'Ne plus afficher automatiquement', exact: true });
    if (await tour.isVisible()) await tour.click();
    await page.getByRole('button', { name: 'Aller à un écran', exact: true }).click();
    await page.getByRole('searchbox', { name: 'Rechercher un écran' }).fill('Équipe & salaires');
    await page.locator('.navigation-palette__results button').filter({ has: page.getByText('Équipe & salaires', { exact: true }) }).click();
    assert.equal(await page.locator('.payslip-list > article').count(), 25);
    const pages = page.getByRole('navigation', { name: 'Pages des fiches de salaire', exact: true });
    await pages.getByRole('button', { name: 'Suivant', exact: true }).click();
    assert.equal(await page.locator('.payslip-list > article').count(), 7);
    const search = page.getByRole('searchbox', { name: 'Rechercher dans Équipe & salaires', exact: true });
    await search.fill('elodie');
    assert.equal(await page.locator('.payslip-list > article').count(), 16);
    assert.equal(await page.locator('.employee-card').count(), 1);
    await page.getByRole('combobox', { name: 'État des fiches de salaire' }).selectOption('paid');
    await page.getByText('Aucune fiche correspondante', { exact: true }).waitFor();
    await page.getByRole('combobox', { name: 'État des fiches de salaire' }).selectOption('all');
    await search.fill('personne-inconnue');
    await page.getByText('Aucun collaborateur correspondant', { exact: true }).waitFor();
    await search.fill('');
    await page.locator('.team-screen').getByRole('button', { name: 'Nouveau collaborateur', exact: true }).click();
    const modal = page.getByRole('dialog');
    await modal.locator('input[name=name]').fill('Alex de recette');
    await modal.locator('input[name=role]').fill('Responsable administratif');
    await modal.locator('input[name=employmentRate]').fill('100');
    await modal.getByRole('combobox', { name: /^Type de rémunération/ }).selectOption('monthly');
    await modal.locator('input[name=grossSalary]').fill('5000');
    await modal.locator('input[name=hourlyCost]').fill('35');
    await modal.locator('select[name=status]').selectOption('actif');
    await modal.locator('input[name=lppAssessmentYear]').fill('2026');
    await modal.getByRole('button', { name: 'Enregistrer', exact: true }).click();
    await modal.getByText(/L’année et le salaire annuel LPP doivent être confirmés ensemble/).waitFor();
    assert.equal((await calls(page, 'employee')).length, 0);
    await modal.locator('input[name=lppAssessmentYear]').fill('');
    await set(page, 'refuse-employee');
    await modal.getByRole('button', { name: 'Enregistrer', exact: true }).click();
    await modal.getByText(/Le numéro de collaborateur existe déjà/).waitFor();
    await page.screenshot({ path: `.qa/payroll-forms/${width}-employee-error.png` });
    await set(page, 'refuse-employee', '0');
    await set(page, 'recover-employee');
    await modal.getByRole('button', { name: 'Enregistrer', exact: true }).click();
    await page.getByRole('dialog', { name: 'Enregistrement effectué', exact: true }).waitFor();
    await set(page, 'fail-reads', '0');
    await page.getByRole('button', { name: 'Actualiser les données', exact: true }).click();
    await page.getByRole('heading', { name: 'Alex de recette', exact: true }).waitFor();
    assert.equal((await calls(page, 'employee')).length, 2);
    await page.getByRole('button', { name: 'Nouvelle fiche', exact: true }).click();
    await modal.getByRole('combobox', { name: /^Collaborateur/ }).selectOption('elodie');
    await modal.locator('input[name=period]').fill('2026-09');
    await modal.getByRole('button', { name: 'Gain', exact: true }).click();
    await modal.getByPlaceholder('Libellé réel').fill('Salaire mensuel');
    const gross = modal.locator('.pay-line-list .money-input input');
    await gross.fill('5000');
    await page.waitForFunction(() => document.querySelectorAll('.contribution-selection-list > article').length === 13);
    for (const checkbox of await modal.locator('.contribution-selection-list input[type=checkbox]').all()) await checkbox.check();
    for (const code of ['AAP_TEST', 'AANP_TEST', 'CAF_TEST']) await modal.locator('.contribution-selection-list > article').filter({ hasText: code }).getByRole('spinbutton', { name: /^Base de calcul/ }).fill('5000');
    await set(page, 'hold-calculate-1');
    await modal.getByRole('button', { name: 'Calculer les cotisations', exact: true }).click();
    await page.waitForFunction(() => sessionStorage.getItem('qa-payroll-waiting-calculate-1') === '1');
    await gross.fill('5100');
    await modal.getByRole('button', { name: 'Calculer les cotisations', exact: true }).click();
    await modal.locator('.payroll-calculation').waitFor();
    const latest = await modal.locator('.payroll-calculation').textContent();
    assert.match(latest, /5.?100[.,]00/);
    await set(page, 'hold-calculate-1', '0');
    await page.waitForFunction(() => !sessionStorage.getItem('qa-payroll-waiting-calculate-1'));
    await page.waitForTimeout(70);
    assert.equal(await modal.locator('.payroll-calculation').textContent(), latest, 'A slow earlier calculation never clears or replaces the current result');
    await modal.locator('input[name=paymentDate]').fill('2026-09-30');
    await page.waitForFunction(() => document.querySelectorAll('.contribution-selection-list input[type=checkbox]:checked').length === 13);
    await set(page, 'fail-rates');
    await modal.locator('input[name=paymentDate]').fill('2026-09-29');
    await modal.getByText(/Les paramètres de cotisation sont momentanément indisponibles/).waitFor();
    assert.equal(await modal.getByRole('button', { name: 'Enregistrer', exact: true }).isEnabled(), false);
    await set(page, 'fail-rates', '0');
    await modal.getByRole('button', { name: 'Réessayer', exact: true }).click();
    await modal.getByRole('button', { name: 'Calculer les cotisations', exact: true }).click();
    await modal.locator('.payroll-calculation').waitFor();
    assert.equal(await modal.locator('.contribution-selection-list input[type=checkbox]:checked').count(), 13);
    assert.equal(await gross.inputValue(), '5100');
    await modal.locator('.document-totals').scrollIntoViewIfNeeded();
    await page.screenshot({ path: `.qa/payroll-forms/${width}-calculation-recovery.png` });
    const geometry = await page.evaluate(() => ({ width: innerWidth, document: document.documentElement.scrollWidth, overflow: [...document.querySelectorAll('.modal,.modal__body')].some((node) => node.scrollWidth > node.clientWidth + 1) }));
    assert.ok(geometry.document <= geometry.width && !geometry.overflow);
    await set(page, 'fail-rates');
    await modal.locator('input[name=paymentDate]').fill('2026-09-30');
    await modal.getByText(/Les paramètres de cotisation sont momentanément indisponibles/).waitFor();
    await modal.getByRole('combobox', { name: /^Collaborateur/ }).selectOption('jean');
    assert.equal(await modal.getByRole('button', { name: 'Enregistrer', exact: true }).isEnabled(), false, 'Changing employee cannot bypass a failed configuration load');
    assert.equal(await modal.getByRole('button', { name: 'Annuler', exact: true }).isEnabled(), true, 'A failed configuration load never pretends a save is running');
    assert.equal((await calls(page, 'save')).length, 0);
    await modal.getByRole('button', { name: 'Annuler', exact: true }).click();
    report.push({ journey: 'PASS payroll search/pagination, employee errors and read-only recovery, stale calculations, preserved selections and configuration retry', width, ...geometry });
    await page.close();
  }
  assert.deepEqual(report.filter((row) => row.error), []);
} catch (error) {
  report.push({ fatal: error.stack }); process.exitCode = 1;
  if (activePage && !activePage.isClosed()) await activePage.screenshot({ path: '.qa/payroll-forms/failure.png' });
} finally { await writeFile('.qa/payroll-forms/report.json', JSON.stringify(report, null, 2)); console.log(JSON.stringify(report, null, 2)); await browser.close(); }
