import { createRequire } from 'node:module';
import { mkdir, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.ZENTRA_PLAYWRIGHT_MODULE || 'playwright');
const browser = await chromium.launch({ headless: true, ...(process.platform === 'win32' ? { channel: 'msedge' } : {}) });
const base = process.env.ZENTRA_QA_URL || 'http://127.0.0.1:5192';
const report = [];
await mkdir('.qa/payroll-pension-corrections', { recursive: true });
let page;
try {
  for (const width of [320, 390, 1440]) {
    page = await browser.newPage({ viewport: { width, height: 900 }, reducedMotion: 'reduce' });
    page.setDefaultTimeout(12000);
    page.on('pageerror', error => report.push({ error: error.stack }));
    await page.goto(`${base}/tests/mobile-harness.html?payroll=1&payrollPensionSetup=1`);
    await page.getByRole('button', { name: 'Fermer le guide automatique', exact: true }).click();
    await page.getByRole('button', { name: 'Aller à un écran', exact: true }).click();
    await page.getByRole('searchbox', { name: 'Rechercher un écran' }).fill('Équipe & salaires');
    await page.locator('.navigation-palette__results button').filter({ has: page.getByText('Équipe & salaires', { exact: true }) }).click();
    await page.locator('.team-navigation').getByRole('button', { name: /Fiches de salaire/ }).click();
    await page.getByRole('button', { name: 'Nouvelle fiche', exact: true }).click();
    const modal = page.getByRole('dialog');
    const setup = modal.locator('.payroll-setup');
    const contracts = setup.locator('.payroll-contracts');
    await modal.getByRole('combobox', { name: /^Collaborateur/ }).selectOption('elodie');
    await modal.locator('input[name=period]').fill('2026-09');
    await modal.getByRole('button', { name: 'Continuer', exact: true }).click();
    const salary = modal.getByRole('spinbutton', { name: 'Salaire brut du mois (CHF)', exact: true });
    await salary.fill('5123.45');
    await modal.getByRole('button', { name: 'Vérifier le salaire', exact: true }).click();
    await modal.locator('textarea[name=notes]').fill('Pension à corriger\nConserver ma saisie');
    await modal.getByRole('button', { name: 'Renseigner le salaire annuel', exact: true }).click();
    assert.equal(await setup.locator('input[name=lppAnnualSalary]').evaluate(node => node === document.activeElement), true);
    await setup.locator('input[name=lppAnnualSalary]').fill('60000');
    await setup.getByRole('button', { name: 'Enregistrer et revenir au salaire', exact: true }).click();
    await setup.waitFor({ state: 'hidden' });
    assert.equal(await modal.getByRole('button', { name: 'Recalculer le salaire', exact: true }).isEnabled(), true);
    await modal.getByRole('button', { name: 'Régler les montants de pension', exact: true }).click();
    assert.equal(await contracts.getByRole('combobox', { name: 'Quelle cotisation souhaitez-vous préparer ?' }).inputValue(), 'lpp');
    await contracts.getByRole('button', { name: 'Compléter le contrat de pension', exact: true }).click();
    assert.equal(await setup.locator('[data-pension-plan]').getAttribute('open'), '');
    await setup.locator('input[name=pensionFund]').fill('Fondation de recette');
    await setup.locator('input[name=contractNumber]').fill('QA-PENSION-2026');
    await setup.getByRole('button', { name: 'Enregistrer et revenir au salaire', exact: true }).click();
    await setup.getByRole('button', { name: 'Ouvrir le contrat de pension', exact: true }).click();
    assert.equal(await setup.locator('input[name=contractNumber]').inputValue(), 'QA-PENSION-2026');
    await setup.locator('input[name=regulationReference]').fill('Règlement QA pension 2026');
    await setup.locator('input[name=lppFrom]').fill('2026-01-01');
    await setup.locator('input[name=lppTo]').fill('2026-12-31');
    await setup.locator('input[name=lppParity]').check();
    await setup.getByRole('button', { name: 'Enregistrer et revenir au salaire', exact: true }).click();
    await setup.waitFor({ state: 'hidden' });
    await modal.getByRole('button', { name: 'Régler les montants de pension', exact: true }).click();
    for (const [side, amount] of [['employee', '245.50'], ['employer', '260']]) {
      await contracts.locator('select[name=side]').selectOption(side);
      await contracts.locator('input[name=amount]').fill(amount);
      await contracts.locator('select[name=component]').selectOption('combined');
      assert.equal(await contracts.locator('input[name=source]').inputValue(), 'Règlement QA pension 2026');
      assert.equal(await contracts.locator('input[name=from]').inputValue(), '2026-01-01');
      await contracts.locator('input[type=checkbox]').check();
      await contracts.getByRole('button', { name: 'Enregistrer cette cotisation', exact: true }).click();
      await contracts.getByRole('button', { name: `Modifier Caisse de pension · ${side === 'employee' ? 'salarié' : 'entreprise'}`, exact: true }).waitFor();
    }
    await contracts.locator('[data-pension-guide]').scrollIntoViewIfNeeded();
    await page.screenshot({ path: `.qa/payroll-pension-corrections/${width}-pension.png` });
    const overflow = await page.evaluate(() => [...document.querySelectorAll('.modal,.modal__body,.payroll-setup,.payroll-pension-guide')].filter(n => n.getClientRects().length).filter(n => n.scrollWidth > n.clientWidth + 1).map(n => n.className));
    assert.deepEqual(overflow, []);
    await setup.getByRole('button', { name: '← Revenir au salaire', exact: true }).click();
    assert.equal(await modal.locator('textarea[name=notes]').inputValue(), 'Pension à corriger\nConserver ma saisie');
    assert.equal(await modal.getByRole('spinbutton', { name: 'Salaire brut du mois (CHF)', exact: true, includeHidden: true }).inputValue(), '5123.45');
    await modal.getByRole('button', { name: 'Appliquer les nouvelles cotisations', exact: true }).click();
    await modal.getByRole('button', { name: 'Recalculer le salaire', exact: true }).click();
    assert.equal(await modal.locator('.payroll-issues').count(), 0);
    await page.evaluate(() => sessionStorage.setItem('qa-payroll-refuse-save', '1'));
    await modal.getByRole('button', { name: 'Enregistrer la fiche', exact: true }).click();
    await modal.getByRole('button', { name: 'Corriger les comptes du salaire', exact: true }).click();
    await setup.locator('select[name=wagesExpenseAccountId]').selectOption('expense-qa');
    await setup.locator('select[name=wagesPayableAccountId]').selectOption('social-qa');
    await setup.getByRole('button', { name: 'Enregistrer et revenir au salaire', exact: true }).click();
    await setup.waitFor({ state: 'hidden' });
    const accountChanges = await page.evaluate(() => JSON.parse(sessionStorage.getItem('qa-payroll-accounting-settings') || '[]'));
    assert.equal(accountChanges.length, 1);
    assert.equal(accountChanges[0].wagesExpenseAccountId, 'expense-qa');
    assert.equal(accountChanges[0].wagesPayableAccountId, 'social-qa');
    await page.evaluate(() => sessionStorage.setItem('qa-payroll-refuse-save', '0'));
    await modal.getByRole('button', { name: 'Recalculer le salaire', exact: true }).click();
    await modal.getByRole('button', { name: 'Enregistrer la fiche', exact: true }).click();
    await modal.waitFor({ state: 'hidden' });
    const saved = await page.evaluate(() => JSON.parse(sessionStorage.getItem('qa-payroll-save') || '[]').at(-1));
    assert.equal(saved.lines[0].amountCents, 512345);
    const definitions = await page.evaluate(() => JSON.parse(sessionStorage.getItem('qa-payroll-definition') || '[]'));
    assert.deepEqual(definitions.map(d => [d.side, d.fixedAmountCents, d.lppEmployeeId]), [['employee', 24550, 'elodie'], ['employer', 26000, 'elodie']]);
    report.push({ width, result: 'PASS annual salary, direct pension routing, invalid plan correction, preserved input, both pension parts, calculation and save' });
    await page.close();
  }
  assert.deepEqual(report.filter(item => item.error), []);
} catch (error) { report.push({ fatal: error.stack }); process.exitCode = 1; if (page && !page.isClosed()) await page.screenshot({ path: '.qa/payroll-pension-corrections/failure.png' }); }
finally { await writeFile('.qa/payroll-pension-corrections/report.json', JSON.stringify(report, null, 2)); console.log(JSON.stringify(report, null, 2)); await browser.close(); }
