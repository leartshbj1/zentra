import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdir, writeFile } from 'node:fs/promises';
const { chromium, webkit } = createRequire(import.meta.url)(process.env.ZENTRA_PLAYWRIGHT_MODULE || 'playwright');
const base = process.env.ZENTRA_QA_URL || 'http://127.0.0.1:5271';
const output = '.qa/recurrence-dates';
await mkdir(output, { recursive: true });
const reports = [];
for (const [engine, driver] of [['edge', chromium], ['webkit', webkit]]) {
  const browser = await driver.launch({ headless: true, ...(engine === 'edge' && process.platform === 'win32' ? { channel: 'msedge' } : {}) });
  try {
    for (const [width, height] of [[320, 568], [390, 844], [844, 390], [1440, 900]]) {
      const page = await browser.newPage({ viewport: { width, height }, reducedMotion: 'reduce' });
      page.setDefaultTimeout(14000);
      const errors = []; page.on('pageerror', error => errors.push(error.message));
      try {
        await page.clock.setFixedTime(new Date('2028-01-15T12:00:00Z'));
        await page.goto(`${base}/tests/mobile-harness.html?browsing=1&recurrence=1`);
        const dismiss = page.getByRole('button', { name: 'Fermer le guide automatique', exact: true });
        await dismiss.click();
        await page.getByRole('button', { name: 'Aller à un écran', exact: true }).click();
        await page.getByRole('searchbox', { name: 'Rechercher un écran' }).fill('Commandes & livraisons');
        await page.locator('.navigation-palette__results button').filter({ has: page.getByText('Commandes & livraisons', { exact: true }) }).click();
        await page.locator('.sales-order-card').first().click();
        const panel = page.locator('.recurring-documents');
        const persisted = () => page.evaluate(() => JSON.parse(sessionStorage.getItem('qa-recurrence-persisted')));
        const originalInvoices = (await persisted()).invoices;
        const updates = () => page.evaluate(() => JSON.parse(sessionStorage.getItem('qa-recurrence-update-attempts') || '[]'));
        const screenshot = async name => { assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false); await page.screenshot({ path: `${output}/${engine}-${width}-${name}.png` }); };
        await panel.getByRole('button', { name: 'Planifier cette commande', exact: true }).click();
        const firstDate = panel.getByLabel('Première échéance', { exact: false });
        await firstDate.fill('2025-01-31');
        assert.equal(await panel.locator('.recurring-calendar__due strong').innerText(), '36 dates déjà arrivées');
        await firstDate.fill('2028-01-31');
        await panel.getByLabel('Délai de paiement', { exact: false }).fill('15');
        assert.deepEqual(await panel.locator('.recurring-calendar li > span time').evaluateAll(nodes => nodes.map(node => node.dateTime)), ['2028-01-31', '2028-02-29', '2028-03-31']);
        assert.equal(await panel.locator('.recurring-calendar li small time').first().getAttribute('datetime'), '2028-02-15');
        await panel.locator('.recurring-calendar').scrollIntoViewIfNeeded(); await screenshot('calendar');
        await panel.getByRole('button', { name: 'Créer la planification', exact: true }).click();
        await panel.getByText('Planification active', { exact: true }).waitFor();
        assert.deepEqual((await persisted()).invoices, originalInvoices);
        const openEditor = async () => { await panel.getByRole('button', { name: 'Modifier la date de fin', exact: true }).click(); return page.getByRole('dialog', { name: 'Modifier la date de fin', exact: true }); };
        let editor = await openEditor();
        assert.equal(await editor.getByRole('button', { name: 'Enregistrer la date de fin', exact: true }).isDisabled(), true, 'Unchanged date creates no write');
        const date = editor.locator('[name=recurringEndDate]');
        await date.fill('2028-01-20');
        await editor.getByRole('button', { name: 'Enregistrer et terminer', exact: true }).click();
        await editor.getByText('La fin doit être à la date de début de la planification ou après.', { exact: true }).waitFor();
        assert.equal(await page.evaluate(() => document.activeElement?.getAttribute('name')), 'recurringEndDate');
        assert.equal((await updates()).length, 0);
        const dateHelp = await editor.getByRole('button', { name: /Utiliser le/ }).evaluate(node => { const rect = node.getBoundingClientRect(), footer = node.closest('form').querySelector('.form-actions').getBoundingClientRect(); return { top: rect.top, bottom: rect.bottom, footer: footer.top }; });
        assert.ok(dateHelp.top >= 0 && dateHelp.bottom <= dateHelp.footer, `Date correction remains visible: ${JSON.stringify(dateHelp)}`);
        await editor.getByRole('button', { name: /Utiliser le/ }).click();
        await date.fill('2028-04-30');
        await page.evaluate(() => sessionStorage.setItem('qa-recurrence-update-failure', 'reject'));
        await editor.getByRole('button', { name: 'Enregistrer la date de fin', exact: true }).click();
        await editor.getByRole('alert').waitFor();
        assert.equal(await date.inputValue(), '2028-04-30');
        await screenshot('retained-error');
        await page.evaluate(() => { sessionStorage.setItem('qa-recurrence-hold-next-update', '1'); sessionStorage.setItem('qa-recurrence-update-failure', 'refresh_twice'); });
        await editor.getByRole('button', { name: 'Enregistrer la date de fin', exact: true }).evaluate(button => { button.click(); button.click(); });
        await page.waitForFunction(() => JSON.parse(sessionStorage.getItem('qa-recurrence-update-attempts')).length === 2);
        assert.equal(await date.isDisabled(), true);
        await page.keyboard.press('Escape'); assert.equal(await editor.count(), 1);
        const attempts = await updates(); assert.equal(attempts[0].requestId, attempts[1].requestId);
        await page.evaluate(() => window.dispatchEvent(new Event('qa-release-recurrence-update')));
        const recovery = page.getByRole('dialog', { name: 'Enregistrement effectué', exact: true });
        await recovery.waitFor();
        await page.evaluate(() => sessionStorage.setItem('qa-recurrence-block-reads', '1'));
        await recovery.getByRole('button', { name: 'Actualiser les données', exact: true }).click();
        await recovery.getByText('Actualisation impossible', { exact: true }).waitFor();
        assert.equal((await updates()).length, 2);
        await page.evaluate(() => sessionStorage.removeItem('qa-recurrence-block-reads'));
        await recovery.getByRole('button', { name: 'Actualiser les données', exact: true }).click();
        await recovery.waitFor({ state: 'detached' }); await editor.waitFor({ state: 'detached' });
        assert.equal((await persisted()).recurrenceSchedules[0].endDate, '2028-04-30');
        assert.equal((await updates()).length, 2);
        await page.clock.setFixedTime(new Date('2028-01-31T12:00:00Z'));
        await page.evaluate(() => window.dispatchEvent(new Event('focus')));
        await page.waitForFunction(count => JSON.parse(sessionStorage.getItem('qa-recurrence-persisted')).invoices.length === count + 1, originalInvoices.length);
        assert.equal((await persisted()).recurrenceSchedules[0].nextScheduledFor, '2028-02-29');
        await panel.getByRole('button', { name: 'Mettre en pause', exact: true }).click();
        await panel.getByText('En pause', { exact: true }).waitFor();
        editor = await openEditor();
        await editor.locator('[name=recurringEndDate]').fill('2028-01-20');
        await editor.getByRole('button', { name: 'Enregistrer et terminer', exact: true }).click();
        assert.ok(await editor.locator('.field__error').isVisible());
        await editor.getByRole('button', { name: /Utiliser le/ }).click();
        await editor.getByText('La planification sera terminée définitivement.', { exact: true }).waitFor();
        await editor.locator('.recurring-editor__outcome').scrollIntoViewIfNeeded();
        await screenshot('permanent-stop-explained');
        await editor.getByRole('button', { name: 'Annuler', exact: true }).click();
        assert.equal((await persisted()).recurrenceSchedules[0].status, 'paused');
        editor = await openEditor(); await editor.locator('[name=recurringEndDate]').fill('');
        await editor.getByRole('button', { name: 'Enregistrer la date de fin', exact: true }).click(); await editor.waitFor({ state: 'detached' });
        assert.equal((await persisted()).recurrenceSchedules[0].endDate, null);
        assert.equal((await persisted()).recurrenceSchedules[0].status, 'paused');
        await panel.getByRole('button', { name: 'Reprendre la planification', exact: true }).click();
        await panel.getByText('Planification active', { exact: true }).waitFor();
        await panel.getByRole('button', { name: 'Terminer définitivement', exact: true }).click();
        const finish = page.getByRole('dialog', { name: 'Terminer cette planification', exact: true });
        await finish.getByRole('button', { name: 'Annuler', exact: true }).click();
        assert.equal((await persisted()).recurrenceSchedules[0].status, 'active');
        editor = await openEditor();
        await editor.locator('[name=recurringEndDate]').fill('2028-01-31');
        await editor.getByText('La planification sera terminée définitivement.', { exact: true }).waitFor();
        await editor.getByRole('button', { name: 'Enregistrer et terminer', exact: true }).click(); await editor.waitFor({ state: 'detached' });
        await panel.getByText('Terminée', { exact: true }).waitFor();
        const final = await persisted(); assert.equal(final.invoices.length, originalInvoices.length + 1); assert.equal(final.invoices.find(row => row.id === final.recurrenceOccurrences[0].invoiceId).status, 'draft');
        assert.equal(final.recurrenceSchedules[0].endDate, '2028-01-31');
        assert.deepEqual(final.invoices.filter(row => originalInvoices.some(original => original.id === row.id)), originalInvoices);
        assert.equal(await panel.getByRole('button', { name: 'Modifier la date de fin', exact: true }).count(), 0);
        const all = await updates(); assert.notEqual(all[1].requestId, all.at(-1).requestId);
        await page.goto(`${base}/tests/mobile-harness.html?browsing=1&recurrence=1&automatic=1&readOnly=1`);
        if (await dismiss.isVisible()) await dismiss.click();
        await page.getByRole('button', { name: 'Aller à un écran', exact: true }).click();
        await page.getByRole('searchbox', { name: 'Rechercher un écran' }).fill('Commandes & livraisons');
        await page.locator('.navigation-palette__results button').filter({ has: page.getByText('Commandes & livraisons', { exact: true }) }).click();
        await page.locator('.sales-order-card').first().click();
        assert.equal(await panel.getByRole('button', { name: 'Modifier la date de fin', exact: true }).isDisabled(), true);
        assert.equal(await panel.getByRole('button', { name: 'Terminer définitivement', exact: true }).isDisabled(), true);
        assert.deepEqual(errors, []);
        reports.push({ engine, width, height, result: 'PASS calendar, pending count, end date, validation, stable retry, retained inputs, locked write, read-only recovery, preserve invoices, pause state and explicit completion' });
      } catch (error) { await page.screenshot({ path: `${output}/${engine}-${width}-failure.png` }); await writeFile(`${output}/${engine}-${width}-failure.html`, await page.content()); reports.push({ engine, width, height, error: error.stack }); throw error; }
      finally { await page.close(); }
    }
  } finally { await browser.close(); await writeFile(`${output}/report.json`, JSON.stringify(reports, null, 2)); }
}
console.log(JSON.stringify(reports, null, 2));
