    await avs.getByRole('button', { name: /FER CIAM.*106.1/ }).click();
    assert.equal(await setup.locator('input[name=avsFund]').inputValue(), 'FER CIAM');
    const accident = setup.locator('.payroll-organisation').filter({ has: page.locator('input[name=accidentInsurer]') });
    await accident.getByRole('button', { name: 'Rechercher dans les caisses suisses', exact: true }).click();
    await accident.getByRole('searchbox').fill('Suva');
    await accident.getByRole('button', { name: /Suva \/ CNA/ }).click();
    const family = setup.locator('.payroll-organisation').filter({ has: page.locator('input[name=familyAllowanceFund]') });
    await family.getByRole('button', { name: 'Rechercher dans les caisses suisses', exact: true }).click();
