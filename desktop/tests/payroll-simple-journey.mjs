    const rejected = (await calls('definition')).at(-1);
    await flag('fail-definition', '0');
    await contracts.getByRole('button', { name: 'Enregistrer cette cotisation', exact: true }).click();
    await contracts.getByRole('button', { name: /Modifier Salaire en cas de maladie/ }).waitFor();
    const recorded = (await calls('definition')).at(-1);
    assert.equal(recorded.id, rejected.id); assert.equal(recorded.rateBp, 125); assert.equal(recorded.category, 'ijm');
    assert.equal(recorded.basisKind, 'ahv_salary'); assert.equal(recorded.annualCeilingCents, null);
