import { createRequire } from 'node:module';
import { mkdir, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.ZENTRA_PLAYWRIGHT_MODULE || 'playwright');
const browser = await chromium.launch({ headless: true, ...(process.platform === 'win32' ? { channel: 'msedge' } : {}) });
const report = [];
await mkdir('.qa/purchase-fulfillment', { recursive: true });
try {
  for (const width of process.env.ZENTRA_QA_WIDTHS ? process.env.ZENTRA_QA_WIDTHS.split(',').map(Number) : [320, 390, 768, 1024, 1440]) {
    const page = await browser.newPage({ viewport: { width, height: 900 } });
    page.setDefaultTimeout(10000);
    page.on('pageerror', (error) => report.push({ width, error: error.message }));
    page.on('dialog', (dialog) => dialog.accept());
    await page.emulateMedia({ reducedMotion: 'reduce' });
    await page.goto('http://127.0.0.1:5175/tests/mobile-harness.html?purchasing=1');
    const tour = page.getByRole('button', { name: 'Ne plus afficher automatiquement', exact: true });
    if (await tour.isVisible()) await tour.click();
    await page.getByRole('button', { name: 'Aller à un écran', exact: true }).click();
    await page.getByRole('searchbox', { name: 'Rechercher un écran' }).fill('Achats');
    await page.locator('.navigation-palette__results button').filter({ has: page.getByText('Achats & fournisseurs', { exact: true }) }).click();
    const section = async (id) => {
      if (width <= 860) await page.getByRole('combobox', { name: 'Section des achats', exact: true }).selectOption(id);
      else await page.locator(`#purchase-tab-${id}`).click();
    };
    const mode = (operation, failure) => page.evaluate(({ operation, failure }) => sessionStorage.setItem(`qa-purchase-${operation}-failure`, failure), { operation, failure });
    const attempts = (operation) => page.evaluate((operation) => JSON.parse(sessionStorage.getItem(`qa-purchase-${operation}-attempts`) || '[]'), operation);
    const persisted = () => page.evaluate(() => JSON.parse(sessionStorage.getItem('qa-purchase-persisted')));
    const capture = async (name, error = false) => {
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `${name}: page overflow ${width}`);
      const dialog = page.getByRole('dialog');
      if (await dialog.count()) assert.ok(await dialog.evaluate((node) => node.scrollWidth <= node.clientWidth + 1 && node.querySelector('.modal__body').scrollWidth <= node.querySelector('.modal__body').clientWidth + 1), `${name}: modal overflow ${width}`);
      const smallText = await page.locator('.purchase-line-editor strong, .purchase-line-editor small, .purchase-line-editor input, .purchase-line-editor select, .purchase-preview small, .purchase-preview p, .purchase-preview strong, .receipt-quantity-grid small, .match-editor small, .match-editor input, .match-editor select').evaluateAll((nodes) => nodes.filter((node) => node.getClientRects().length && parseFloat(getComputedStyle(node).fontSize) < 12).map((node) => node.textContent));
      assert.deepEqual(smallText, [], `${name}: readable quantities and purchase details at ${width}`);
      if (error) {
        await page.waitForFunction(() => {
          const dialog = document.querySelector('[role="dialog"]');
          const panel = dialog?.querySelector('.error-panel'); const body = dialog?.querySelector('.modal__body'); const actions = dialog?.querySelector('.form-actions');
          if (!panel || !body || !actions) return false;
          const rect = panel.getBoundingClientRect(); const frame = body.getBoundingClientRect(); const footer = actions.getBoundingClientRect();
          return rect.top >= Math.max(0, frame.top, dialog.querySelector('.modal__header').getBoundingClientRect().bottom) - 1 && rect.bottom <= Math.min(innerHeight, frame.bottom, footer.top) + 1 && footer.bottom <= Math.min(innerHeight, frame.bottom, dialog.getBoundingClientRect().bottom) + 1;
        }).catch(async (error) => {
          report.push({ width, screen: name, geometry: await page.evaluate(() => {
            const body = document.querySelector('[role="dialog"] .modal__body');
            return { scrollTop: body.scrollTop, scrollHeight: body.scrollHeight, clientHeight: body.clientHeight, elements: ['.modal__body', '.error-panel', '.form-actions'].map((selector) => { const node = document.querySelector(`[role="dialog"] ${selector}`); const rect = node.getBoundingClientRect(); return { selector, top: rect.top, bottom: rect.bottom, height: rect.height, position: getComputedStyle(node).position }; }) };
          }) }); throw error;
        });
        assert.equal(await page.locator('.notice--floating').count(), 0, 'no duplicate error over the dialog heading');
      }
      await page.screenshot({ path: `.qa/purchase-fulfillment/${width}-${name}.png` });
    };
    await section('orders');
    await page.getByRole('button', { name: 'Nouvelle commande', exact: true }).click();
    let dialog = page.getByRole('dialog');
    await dialog.getByRole('textbox', { name: /^Titre/ }).fill('Réaménagement du bureau de Lausanne');
    await dialog.getByLabel('Date', { exact: false }).fill('2026-09-01');
    await dialog.getByRole('combobox', { name: 'Article du catalogue', exact: true }).selectOption('product-purchase-qa');
    assert.equal(await dialog.getByRole('combobox', { name: 'TVA %', exact: true }).inputValue(), '8.1', 'selected rate matches the amount used in totals');
    await dialog.getByRole('spinbutton', { name: /^Quantité/ }).fill('10');
    await dialog.getByLabel('Catégorie', { exact: false }).fill('Marchandises');
    await dialog.getByRole('textbox', { name: 'Notes', exact: true }).fill('Livraison à l’accueil du bureau');
    await mode('order', 'reject');
    await dialog.getByRole('button', { name: 'Enregistrer le brouillon', exact: true }).click();
    await dialog.getByText('Refus order : la période comptable est fermée.', { exact: true }).waitFor();
    await capture('order-refused', true);
    await mode('order', 'refresh_twice');
    await dialog.getByRole('button', { name: 'Enregistrer le brouillon', exact: true }).click();
    await page.getByRole('dialog', { name: 'Enregistrement effectué', exact: true }).waitFor();
    assert.equal((await persisted()).orders, 1);
    await page.getByRole('button', { name: 'Actualiser les données', exact: true }).click();
    await dialog.waitFor({ state: 'detached' });
    const orderAttempts = await attempts('order');
    assert.equal(orderAttempts.length, 2); assert.ok(orderAttempts[0].id);
    assert.equal(new Set(orderAttempts.map((input) => input.id)).size, 1);
    assert.ok(orderAttempts.every((input) => input.lines[0].quantityMilli === 10000 && input.notes === 'Livraison à l’accueil du bureau'));
    assert.equal((await persisted()).orders, 1); assert.equal((await persisted()).stock, 5000);
    await capture('order-saved');
    await page.getByRole('button', { name: 'Contrôler et confirmer', exact: true }).click();
    dialog = page.getByRole('dialog');
    await mode('confirm', 'reject');
    await dialog.getByRole('button', { name: 'Confirmer la commande', exact: true }).click();
    await dialog.getByText('Refus confirm : la période comptable est fermée.', { exact: true }).waitFor();
    await capture('confirmation-refused', true);
    await mode('confirm', 'refresh_once');
    await dialog.getByRole('button', { name: 'Confirmer la commande', exact: true }).click();
    await dialog.waitFor({ state: 'detached' });
    const confirms = await attempts('confirm'); assert.equal(confirms.length, 2); assert.equal(confirms[0].requestId, confirms[1].requestId);
    await page.getByRole('button', { name: 'Saisir la réception', exact: true }).click();
    dialog = page.getByRole('dialog');
    await dialog.getByLabel('Date de réception', { exact: false }).fill('2026-09-02');
    await dialog.getByRole('spinbutton', { name: /^Quantité reçue pour/ }).fill('2');
    await dialog.getByRole('textbox', { name: 'Référence', exact: true }).fill('BL-FOURNISSEUR-2026-0092');
    await dialog.getByRole('textbox', { name: 'Notes', exact: true }).fill('Deux panneaux reçus et contrôlés');
    await mode('receipt', 'reject');
    await dialog.getByRole('button', { name: 'Enregistrer le brouillon', exact: true }).click();
    await dialog.getByText('Refus receipt : la période comptable est fermée.', { exact: true }).waitFor();
    await capture('receipt-refused', true);
    await mode('receipt', 'refresh_twice');
    await dialog.getByRole('button', { name: 'Enregistrer le brouillon', exact: true }).click();
    await page.getByRole('dialog', { name: 'Enregistrement effectué', exact: true }).waitFor();
    await capture('receipt-awaiting-refresh');
    await page.getByRole('button', { name: 'Actualiser les données', exact: true }).click();
    await dialog.waitFor({ state: 'detached' });
    const receipts = await attempts('receipt'); assert.equal(receipts.length, 2); assert.ok(receipts[0].id); assert.equal(new Set(receipts.map((input) => input.id)).size, 1);
    assert.ok(receipts.every((input) => input.reference === 'BL-FOURNISSEUR-2026-0092' && input.lines[0].quantityMilli === 2000));
    assert.equal((await persisted()).receipts, 1); assert.equal((await persisted()).stock, 5000);
    await page.getByRole('button', { name: 'Contrôler la réception', exact: true }).click();
    dialog = page.getByRole('dialog');
    await mode('issue', 'reject');
    await dialog.getByRole('button', { name: 'Émettre la réception', exact: true }).click();
    await dialog.getByText('Refus issue : la période comptable est fermée.', { exact: true }).waitFor();
    await capture('issue-refused', true);
    await mode('issue', 'refresh_twice');
    await dialog.getByRole('button', { name: 'Émettre la réception', exact: true }).click();
    await page.getByRole('dialog', { name: 'Enregistrement effectué', exact: true }).waitFor();
    await page.getByRole('button', { name: 'Actualiser les données', exact: true }).click();
    await dialog.waitFor({ state: 'detached' });
    const issues = await attempts('issue'); assert.equal(issues.length, 2); assert.equal(new Set(issues.map((input) => input.requestId)).size, 1);
    assert.equal((await persisted()).stock, 7000); assert.equal((await persisted()).issued, 1);
    await section('receipts');
    await page.getByRole('button', { name: 'Extourner', exact: true }).click();
    dialog = page.getByRole('dialog');
    await dialog.getByRole('textbox', { name: /^Motif de la correction/ }).fill('Retour signalé par le fournisseur');
    await mode('reverse', 'reject');
    await dialog.getByRole('button', { name: 'Confirmer l’extourne', exact: true }).click();
    await dialog.getByText('Refus reverse : la période comptable est fermée.', { exact: true }).waitFor();
    await capture('reversal-refused', true);
    assert.equal(await dialog.getByRole('textbox', { name: /^Motif de la correction/ }).inputValue(), 'Retour signalé par le fournisseur');
    await dialog.getByRole('button', { name: 'Annuler', exact: true }).click();
    await section('documents');
    await page.getByRole('button', { name: 'Rapprocher avant validation', exact: true }).click();
    dialog = page.getByRole('dialog');
    await mode('match', 'reject');
    await dialog.getByRole('button', { name: 'Enregistrer le rapprochement', exact: true }).click();
    await dialog.getByText('Refus match : la période comptable est fermée.', { exact: true }).waitFor();
    await capture('match-refused', true);
    await mode('match', 'refresh_once');
    await dialog.getByRole('button', { name: 'Enregistrer le rapprochement', exact: true }).click();
    await dialog.waitFor({ state: 'detached' });
    const matches = await attempts('match'); assert.equal(matches.length, 2); assert.equal(matches[0].requestId, matches[1].requestId);
    assert.equal(matches[1].allocations.length, 1); assert.equal(matches[1].allocations[0].quantityMilli, 2000); assert.ok(matches[1].allocations[0].supplierReceiptLineId);
    assert.equal((await persisted()).matches.length, 1); assert.equal((await persisted()).stock, 7000);
    await capture('invoice-matched');
    await mode('validate', 'refresh_once');
    await page.getByRole('button', { name: 'Valider', exact: true }).click();
    await page.getByRole('button', { name: 'Paiement', exact: true }).waitFor();
    assert.equal((await attempts('validate')).length, 1); assert.equal((await persisted()).validated, 1); assert.equal((await persisted()).stock, 7000);
    await capture('invoice-validated');
    report.push({ width, result: 'PASS purchase order, confirmation, partial receipt, refusal and retries, stock unchanged by drafts or invoice, linked invoice validation, stable IDs, visible errors and no overflow' });
    await page.close();
  }
  for (const width of [320, 1440]) {
    const page = await browser.newPage({ viewport: { width, height: 900 } });
    page.on('pageerror', (error) => report.push({ width, error: error.message }));
    await page.emulateMedia({ reducedMotion: 'reduce' });
    await page.goto('http://127.0.0.1:5175/tests/mobile-harness.html?purchasing=1&oldVat=1');
    const tour = page.getByRole('button', { name: 'Ne plus afficher automatiquement', exact: true });
    if (await tour.isVisible()) await tour.click();
    await page.getByRole('button', { name: 'Aller à un écran', exact: true }).click();
    await page.getByRole('searchbox', { name: 'Rechercher un écran' }).fill('Achats');
    await page.locator('.navigation-palette__results button').filter({ has: page.getByText('Achats & fournisseurs', { exact: true }) }).click();
    await page.getByRole('button', { name: 'Nouvelle commande', exact: true }).click();
    const dialog = page.getByRole('dialog');
    await dialog.getByRole('combobox', { name: 'Article du catalogue', exact: true }).selectOption('product-purchase-qa');
    await dialog.getByRole('spinbutton', { name: /^Quantité/ }).fill('10');
    const rate = dialog.getByRole('combobox', { name: /^TVA %/ });
    assert.equal(await rate.inputValue(), '8.1');
    assert.match(await rate.locator('option:checked').innerText(), /8,1 % \(à vérifier\)/);
    await dialog.getByText('Ce taux n’est plus configuré. Choisissez un taux disponible.', { exact: true }).waitFor();
    assert.ok(await dialog.getByRole('button', { name: 'Enregistrer le brouillon', exact: true }).isDisabled());
    await rate.scrollIntoViewIfNeeded();
    await page.screenshot({ path: `.qa/purchase-fulfillment/${width}-old-vat-visible.png` });
    await rate.selectOption('0');
    await dialog.getByRole('button', { name: 'Enregistrer le brouillon', exact: true }).click();
    await dialog.waitFor({ state: 'detached' });
    const attempts = await page.evaluate(() => JSON.parse(sessionStorage.getItem('qa-purchase-order-attempts') || '[]'));
    assert.equal(attempts.length, 1); assert.equal(attempts[0].lines[0].vatBp, 0);
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    report.push({ width, result: 'PASS unconfigured catalog VAT stays visible at 8.1%, explicit field warning, save disabled until the user selects an allowed rate, submitted rate matches the selection' });
    await page.close();
  }
  assert.deepEqual(report.filter((item) => item.error), []);
} catch (error) {
  report.push({ fatal: error.stack }); process.exitCode = 1;
  const page = browser.contexts().flatMap((context) => context.pages()).at(-1);
  if (page) { await page.screenshot({ path: '.qa/purchase-fulfillment/failure.png', fullPage: true }); await writeFile('.qa/purchase-fulfillment/failure.html', await page.content()); }
} finally {
  await writeFile('.qa/purchase-fulfillment/report.json', JSON.stringify(report, null, 2));
  console.log(JSON.stringify(report, null, 2)); await browser.close();
}
