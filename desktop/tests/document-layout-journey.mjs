import { createRequire } from 'node:module';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import assert from 'node:assert/strict';
const engine = process.env.ZENTRA_QA_ENGINE || 'chromium';
const driver = createRequire(import.meta.url)(process.env.ZENTRA_PLAYWRIGHT_MODULE || 'playwright')[engine];
const browser = await driver.launch({ headless: true, ...(engine === 'chromium' && process.platform === 'win32' ? { channel: 'msedge' } : {}) });
const folder = `.qa/document-layout-${engine}`;
await mkdir(folder, { recursive: true });
const report = [];
try {
  for (const [width, height] of [[320,568],[390,844],[844,390],[1440,1000]]) {
    const page = await browser.newPage({ viewport: { width, height }, reducedMotion: 'reduce' });
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    await page.route('**/native-design-fixture/*.pdf', async route => {
      const name = new URL(route.request().url()).pathname.split('/').at(-1);
      assert.match(name, /^(quotes|invoices|accounts|payslips)-(signature|minimal|helvetica|times|courier)\.pdf$/);
      const kind = name.split('-')[0];
      const draft = await page.evaluate(() => JSON.parse(sessionStorage.getItem('design-request') || '{}'));
      const file = draft.style?.composition?.closingOnNewPage ? `.qa/layout-pdfs/${kind}-layout.pdf` : `.qa/composition-pdfs/${name}`;
      await route.fulfill({ contentType: 'application/pdf', body: await readFile(file) });
    });
    await page.goto(`${process.env.ZENTRA_QA_ORIGIN || 'http://127.0.0.1:5271'}/tests/document-design-harness.html?tools=1`);
    const ready = () => page.locator('.design-studio__preview[aria-busy=false] .design-studio__pages img').first().waitFor({ timeout: 30000 });
    const state = () => page.evaluate(() => JSON.parse(sessionStorage.getItem('design-draft') || '{}'));
    const history = page.getByRole('group', { name: 'Historique de la présentation' });
    await ready();
    for (const [kind, label] of [['invoices','Factures'],['quotes','Devis'],['accounts','Bilan'],['payslips','Fiches de salaire']]) {
      await page.getByRole('button', { name: label, exact: true }).click();
      await page.getByRole('button', { name: 'Style', exact: true }).click();
      await page.getByLabel('Police du document', { exact: true }).selectOption('times');
      const inks = page.locator('details').filter({ has: page.getByText('Couleurs du titre et du texte', { exact: true }) });
      if (!await inks.evaluate(el => el.open)) await inks.locator('summary').click();
      await page.getByLabel('Couleur du texte du document', { exact: true }).fill('#182b49');
      await page.getByLabel('Couleur du titre du document', { exact: true }).fill('#793c32');
      await page.getByRole('button', { name: 'Mise en page', exact: true }).click();
      const layout = page.locator('details').filter({ has: page.getByText('Ajuster les blocs et les espacements', { exact: true }) });
      if (!await layout.evaluate(el => el.open)) await layout.locator('summary').click();
      await page.getByLabel('Alignement de l’entreprise', { exact: true }).selectOption('center');
      if (kind !== 'accounts') await page.getByLabel('Alignement du destinataire', { exact: true }).selectOption('right');
      else assert.equal(await page.getByLabel('Alignement du destinataire', { exact: true }).count(), 0);
      await page.getByLabel('Espace sous le logo', { exact: true }).selectOption('24');
      await page.getByLabel('Début du contenu', { exact: true }).selectOption('25');
      await page.getByLabel('Espace entre les blocs', { exact: true }).selectOption('0.5');
      await page.getByLabel('Position du logo', { exact: true }).selectOption('center');
      await page.getByRole('button', { name: 'Textes', exact: true }).click();
      await page.getByLabel('Zone de texte', { exact: true }).selectOption('closing');
      const editor = page.getByRole('textbox', { name: kind === 'accounts' ? 'Commentaire après les comptes' : 'Conditions et message de fin', exact: true });
      await editor.fill('Conditions distinctes de recette');
      await editor.press('Control+a'); await editor.press('Control+b');
      await page.getByRole('button', { name: 'Mise en page', exact: true }).click();
      await page.getByRole('checkbox', { name: /Commencer les .* sur une nouvelle page/ }).check();
      await ready();
      let design = (await state()).documentComposition[kind];
      assert.equal(design.companyAlign, 'center'); assert.equal(design.topMarginMm, 25);
      assert.equal(design.logoGap, 24); assert.equal(design.blockSpacing, .5);
      assert.equal(design.textColor, '#182b49'); assert.equal(design.titleColor, '#793c32');
      assert.equal(design.closingOnNewPage, true); assert.ok(design.closing[0].runs[0].bold);
      await history.getByRole('button', { name: 'Annuler', exact: true }).click();
      assert.equal((await state()).documentComposition[kind].closingOnNewPage, undefined);
      await history.getByRole('button', { name: 'Rétablir', exact: true }).click(); await ready();
      await page.evaluate(() => window.dispatchEvent(new CustomEvent('design-fixture-update', { detail: { busy: true } })));
      await page.waitForFunction(() => document.querySelector('[aria-label="Alignement de l’entreprise"]').matches(':disabled'));
      assert.equal(await page.getByLabel('Alignement de l’entreprise', { exact: true }).isDisabled(), true);
      assert.equal(await history.getByRole('button', { name: 'Enregistrer', exact: true }).isDisabled(), true);
      await page.evaluate(() => window.dispatchEvent(new CustomEvent('design-fixture-update', { detail: { busy: false } })));
      await page.waitForFunction(() => !document.querySelector('[aria-label="Alignement de l’entreprise"]').matches(':disabled'));
      await history.getByRole('button', { name: 'Aperçu', exact: true }).click();
      await page.waitForFunction(() => document.querySelector('.design-studio__preview').getBoundingClientRect().top < 120);
      await page.screenshot({ path: `${folder}/${width}-${kind}-preview.png` });
      await page.getByRole('button', { name: 'Revenir aux réglages', exact: true }).click();
      await page.waitForFunction(() => document.activeElement.matches('.design-studio__panels button[aria-pressed=true]'));
      assert.equal(await page.getByRole('button', { name: 'Mise en page', exact: true }).evaluate(el => el === document.activeElement), true);
      await page.getByLabel('Alignement de l’entreprise', { exact: true }).scrollIntoViewIfNeeded();
      await page.screenshot({ path: `${folder}/${width}-${kind}-controls.png` });
      await page.getByRole('button', { name: 'Exporter cet exemple', exact: true }).click();
      const exported = await page.evaluate(() => JSON.parse(sessionStorage.getItem('design-export')));
      assert.deepEqual(exported.style.composition, (await state()).documentComposition[kind]);
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false);
    }
    await ready();
    await history.getByRole('button', { name: 'Enregistrer', exact: true }).click(); await page.getByText('Les présentations sont enregistrées.', { exact: true }).waitFor();
    const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('design-settings')));
    await page.reload(); await ready();
    const request = await page.evaluate(() => JSON.parse(sessionStorage.getItem('design-request')));
    assert.deepEqual(request.style.composition, saved.documentComposition.invoices);
    await page.getByRole('button', { name: 'Mise en page', exact: true }).click();
    await page.getByText('Ajuster les blocs et les espacements', { exact: true }).click();
    await page.getByLabel('Début du contenu', { exact: true }).selectOption('');
    assert.equal((await state()).documentComposition.invoices.topMarginMm, undefined);
    await page.getByRole('button', { name: 'Style', exact: true }).click();
    await page.getByText('Couleurs du titre et du texte', { exact: true }).click();
    await page.getByRole('button', { name: 'Titre assorti aux tableaux', exact: true }).click();
    await page.getByRole('button', { name: 'Texte en couleur automatique', exact: true }).click();
    assert.equal((await state()).documentComposition.invoices.textColor, undefined);
    assert.equal((await state()).documentComposition.invoices.titleColor, undefined);
    assert.deepEqual(errors, []);
    report.push({ width, height, categories: 4, engine, passed: true });
    await page.close();
  }
} catch(error) { report.push({ error: String(error.stack || error) }); process.exitCode = 1; }
finally { await writeFile(`${folder}/report.json`, JSON.stringify(report, null, 2)); console.log(JSON.stringify(report)); await browser.close(); }
