import { createRequire } from 'node:module';
import { readFile, mkdir, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
const engine = process.env.ZENTRA_QA_ENGINE || 'chromium';
const driver = createRequire(import.meta.url)(process.env.ZENTRA_PLAYWRIGHT_MODULE || 'playwright')[engine];
const browser = await driver.launch({ headless: true, ...(engine === 'chromium' && process.platform === 'win32' ? { channel: 'msedge' } : {}) });
const folder = `.qa/document-text-colors-${engine}`;
await mkdir(folder, { recursive: true });
const report = [];
try {
  for (const width of [1440, 390, 320]) {
    const page = await browser.newPage({ viewport: { width, height: 900 }, reducedMotion: 'reduce' });
    const errors = []; page.on('pageerror', e => errors.push(e.message));
    await page.route('**/native-design-fixture/*.pdf', async route => {
      const file = new URL(route.request().url()).pathname.split('/').at(-1);
      assert.match(file, /^(quotes|invoices|accounts|payslips)-(signature|minimal|helvetica|times|courier)\.pdf$/);
      await route.fulfill({ contentType: 'application/pdf', body: await readFile(`.qa/composition-pdfs/${file}`) });
    });
    await page.goto(`${process.env.ZENTRA_QA_ORIGIN || 'http://127.0.0.1:5271'}/tests/document-design-harness.html`);
    const ready = () => page.locator('.design-studio__preview[aria-busy=false] .design-studio__pages img').first().waitFor({ timeout: 30000 });
    await ready();
    await page.getByRole('button', { name: 'Textes', exact: true }).click();
    const editor = page.getByRole('textbox', { name: 'Conditions et message de fin', exact: true });
    const toolbar = page.getByRole('group', { name: 'Mise en forme : Conditions et message de fin', exact: true });
    const button = name => toolbar.getByRole('button', { name, exact: true });
    const value = () => page.evaluate(() => JSON.parse(sessionStorage.getItem('design-draft')).documentComposition.invoices.closing);
    const select = async (start, end) => editor.evaluate((el, { start, end }) => {
      const nodes = []; const walker = document.createTreeWalker(el, NodeFilter.SHOW_TEXT);
      while (walker.nextNode()) nodes.push(walker.currentNode);
      const point = offset => { for (const n of nodes) { if (offset <= n.length) return [n, offset]; offset -= n.length; } throw Error('Selection outside text'); };
      const range = document.createRange(); range.setStart(...point(start)); range.setEnd(...point(end));
      el.focus(); const selection = getSelection(); selection.removeAllRanges(); selection.addRange(range);
    }, { start, end });
    await editor.fill('Paiement sous 30 jours.'); await select(9, 16);
    await button('Gras').click(); await button('Couleur du texte').click();
    const palette = page.getByRole('group', { name: 'Choisir la couleur du texte', exact: true });
    await palette.getByRole('button', { name: 'Bordeaux', exact: true }).click();
    assert.deepEqual((await value())[0].runs.map(r => [r.text, !!r.bold, r.color]), [['Paiement ', false, undefined], ['sous 30', true, '#793c32'], [' jours.', false, undefined]]);
    await button('Surligner le texte').click();
    await page.getByRole('group', { name: 'Choisir le surlignage', exact: true }).getByRole('button', { name: 'Jaune', exact: true }).click();
    assert.equal((await value())[0].runs[1].highlight, '#fff0a6');
    assert.equal(await editor.locator('[data-color="#793c32"]').evaluate(el => getComputedStyle(el).color), 'rgb(121, 60, 50)');
    assert.equal(await editor.locator('[data-highlight="#fff0a6"]').evaluate(el => getComputedStyle(el).backgroundColor), 'rgb(255, 240, 166)');
    await button('Effacer la mise en forme').click();
    assert.equal((await value())[0].runs.length, 1);
    assert.equal((await value())[0].runs[0].text, 'Paiement sous 30 jours.');
    await button('Annuler la modification du texte').click();
    assert.equal((await value())[0].runs[1].highlight, '#fff0a6');
    await select(23, 23); await button('Couleur du texte').click();
    await palette.getByRole('button', { name: 'Bleu marine', exact: true }).click();
    await editor.pressSequentially(' Merci.');
    assert.equal((await value())[0].runs.at(-1).color, '#182b49');
    await select(9, 16); await button('Surligner le texte').click();
    await page.getByRole('group', { name: 'Choisir le surlignage', exact: true }).getByRole('button', { name: 'Sans surlignage', exact: true }).click();
    assert.equal((await value())[0].runs[1].highlight, undefined);
    assert.equal((await value())[0].runs[1].color, '#793c32');
    await button('Annuler la modification du texte').click();
    await ready(); await page.getByRole('button', { name: 'Enregistrer les présentations', exact: true }).click();
    await page.reload(); await ready();
    const saved = await page.evaluate(() => JSON.parse(sessionStorage.getItem('design-request')).style.composition.closing);
    assert.ok(saved[0].runs.some(r => r.text === 'sous 30' && r.color === '#793c32' && r.highlight === '#fff0a6'));
    await page.getByText('Réutiliser cette présentation', { exact: true }).click();
    await page.getByLabel('Copier vers', { exact: true }).selectOption('accounts');
    await page.getByRole('button', { name: 'Copier la présentation', exact: true }).click();
    await page.getByRole('button', { name: 'Bilan', exact: true }).click(); await ready();
    await page.getByRole('button', { name: 'Exporter cet exemple', exact: true }).click();
    assert.deepEqual(await page.evaluate(() => JSON.parse(sessionStorage.getItem('design-export')).style.composition.closing), saved);
    await page.getByRole('button', { name: 'Textes', exact: true }).click();
    await page.getByRole('group', { name: 'Mise en forme : Commentaire après les comptes', exact: true }).getByRole('button', { name: 'Surligner le texte', exact: true }).click();
    await page.locator('.rich-editor').scrollIntoViewIfNeeded();
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false);
    await page.screenshot({ path: `${folder}/${width}.png`, fullPage: true });
    assert.deepEqual(errors, []);
    report.push({ width, selection: true, typing: true, clearUndo: true, saveReload: true, accountsCopyExport: true, noOverflow: true });
    await page.close();
  }
  await writeFile(`${folder}/report.json`, JSON.stringify({ engine, report }, null, 2));
  console.log(JSON.stringify({ engine, report }));
} finally { await browser.close(); }
