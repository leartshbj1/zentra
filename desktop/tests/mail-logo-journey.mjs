import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdir, writeFile } from 'node:fs/promises';
const { chromium, webkit } = createRequire(import.meta.url)(process.env.ZENTRA_PLAYWRIGHT_MODULE || 'playwright');
const origin = process.env.ZENTRA_QA_ORIGIN || 'http://127.0.0.1:5331';
const output = '.impeccable/review/mail-logo';
await mkdir(output, { recursive: true });
const results = [];
for (const [engine,type] of [['edge',chromium],['webkit',webkit]]) {
  const browser = await type.launch({ headless: true, ...(engine==='edge'&&process.platform==='win32'?{channel:'msedge'}:{}) });
  try { for (const width of [390,1440]) {
    const page = await browser.newPage({viewport:{width,height:950},reducedMotion:'reduce'});
    // Local HTTP fixture only; production CSP is unchanged.
    await page.route(`${origin}/**`,async route=>{const response=await route.fetch();const headers={...response.headers()};if(headers['content-security-policy'])headers['content-security-policy']=headers['content-security-policy'].replace(/upgrade-insecure-requests;?/g,'');await route.fulfill({response,headers});});
    const errors=[];page.on('pageerror',e=>errors.push(e.message));
    const theme=width===390?'dark':'light';
    await page.goto(`${origin}/tests/outgoing-mail-preview.html?connected&theme=${theme}`);
    await page.getByRole('button',{name:'Factures',exact:true}).click();
    const toggle=page.getByRole('switch',{name:/Ajouter le logo/});
    assert.equal(await toggle.isChecked(),false);
    await toggle.check();
    await page.getByRole('button',{name:'Enregistrer les modèles'}).click();
    await page.getByText('Modèles enregistrés pour l’entreprise.',{exact:true}).waitFor();
    await page.getByRole('button',{name:'Devis',exact:true}).click();
    assert.equal(await toggle.isChecked(),true);
    const logo=page.locator('.mail-signature-paper img');
    await logo.waitFor();assert.equal(await logo.evaluate(e=>e.complete&&e.naturalWidth>0),true);
    assert.equal(await page.locator('.mail-signature-paper').evaluate(e=>getComputedStyle(e).backgroundColor),'rgb(255, 255, 255)');
    await page.screenshot({path:`${output}/settings-${engine}-${width}.png`,fullPage:true});
    await page.getByRole('button',{name:'Préparer un e-mail'}).click();
    const dialog=page.getByRole('dialog',{name:'Envoyer par e-mail'});
    await dialog.getByRole('button',{name:'Envoyer l’e-mail',exact:true}).scrollIntoViewIfNeeded();
    assert.equal(await dialog.locator('.mail-signature-paper img').count(),1);
    assert.equal(await dialog.getByRole('button',{name:'Envoyer l’e-mail',exact:true}).isEnabled(),true);
    await page.screenshot({path:`${output}/composer-${engine}-${width}.png`,fullPage:true});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1),false);
    await dialog.getByRole('button',{name:'Annuler',exact:true}).click();
    await toggle.uncheck();await page.getByRole('button',{name:'Enregistrer les modèles'}).click();
    await page.getByText('Modèles enregistrés pour l’entreprise.',{exact:true}).waitFor();
    await page.getByRole('button',{name:'Préparer un e-mail'}).click();
    await dialog.getByRole('textbox',{name:/^Message/}).waitFor();
    assert.equal(await dialog.locator('.mail-signature-paper img').count(),0);
    assert.equal(await page.evaluate(()=>window.__mailQa.sends),0);
    await page.goto(`${origin}/tests/outgoing-mail-preview.html?connected&composer&noLogo&logo&theme=${theme}`);
    await dialog.getByRole('button',{name:'Modifier les réglages des e-mails'}).click();
    const settings=page.getByRole('dialog',{name:'Votre messagerie'});
    await settings.getByRole('switch',{name:/Ajouter le logo/}).uncheck();
    await settings.getByRole('button',{name:'Enregistrer les modèles'}).click();
    await settings.getByText('Modèles enregistrés pour l’entreprise.',{exact:true}).waitFor();
    await settings.getByRole('button',{name:'Revenir au message'}).click();
    await dialog.getByRole('textbox',{name:/^Message/}).waitFor();
    assert.equal(await dialog.getByRole('button',{name:'Envoyer l’e-mail',exact:true}).isEnabled(),true);
    assert.equal(await dialog.locator('.mail-signature-issue').count(),0);
    await page.goto(`${origin}/tests/outgoing-mail-preview.html?composer`);
    await dialog.getByRole('textbox',{name:/^Message/}).fill('Message personnel conservé.');
    await dialog.getByRole('button',{name:'Connecter ma messagerie',exact:true}).click();
    await settings.getByLabel('Mot de passe de la boîte mail',{exact:false}).fill('FAKE-UI-TEST');
    await settings.getByRole('button',{name:'Connecter ma messagerie',exact:true}).click();
    await settings.getByText('Connexion vérifiée et enregistrée.',{exact:false}).waitFor();
    await settings.getByRole('button',{name:'Revenir au message'}).click();
    assert.equal(await dialog.getByRole('textbox',{name:/^Message/}).inputValue(),'Message personnel conservé.');
    await page.goto(`${origin}/tests/outgoing-mail-preview.html?connected&noLogo`);
    await page.getByRole('button',{name:'Devis',exact:true}).click();
    assert.equal(await toggle.isDisabled(),true);
    await page.getByText('Ajoutez votre logo dans Paramètres → Entreprise pour l’utiliser ici.',{exact:true}).waitFor();
    await page.goto(`${origin}/tests/outgoing-mail-preview.html?connected&readOnly&logo`);
    await page.getByRole('button',{name:'Devis',exact:true}).click();
    assert.equal(await toggle.isDisabled(),true);
    assert.equal(await page.evaluate(()=>window.__mailQa.sends),0);
    assert.deepEqual(errors,[]);
    results.push({engine,width,theme,sharedPreference:true,preview:true,disabledLogoOmitted:true,missingLogoRecovery:true,readOnlyRespected:true,noEmailsSent:true,noOverflow:true,errors});
    await page.close();
  }} finally { await browser.close(); }
}
await writeFile(`${output}/results.json`,JSON.stringify(results,null,2));
console.log(JSON.stringify(results));
