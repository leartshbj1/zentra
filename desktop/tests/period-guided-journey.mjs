import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdir, writeFile } from 'node:fs/promises';
import { expandAccountingPeriodFilters } from './accounting-navigation.mjs';
const { chromium, webkit } = createRequire(import.meta.url)(process.env.ZENTRA_PLAYWRIGHT_MODULE || 'playwright');
const base = process.env.ZENTRA_QA_URL || 'http://127.0.0.1:5271';
const output = '.qa/period-guided', reports = [];
await mkdir(output, { recursive: true });
for (const [engine, driver] of [['edge', chromium], ['webkit', webkit]]) {
  const browser = await driver.launch({ headless: true, ...(engine === 'edge' && process.platform === 'win32' ? { channel: 'msedge' } : {}) });
  try {
    for (const [width, height] of [[320, 568], [390, 844], [844, 390], [1440, 900]]) {
      const page = await browser.newPage({ viewport: { width, height }, reducedMotion: 'reduce' });
      page.setDefaultTimeout(14000);
      const errors = []; page.on('pageerror', error => errors.push(error.message));
      page.on('dialog', async dialog => { errors.push('Unexpected native confirmation'); await dialog.dismiss(); });
      const calls = name => page.evaluate(name => JSON.parse(sessionStorage.getItem(`qa-closing-${name}`) || '[]'), name);
      const flag = (name, value = '1') => page.evaluate(([name, value]) => sessionStorage.setItem(`qa-closing-${name}`, value), [name, value]);
      const snapshot = () => page.evaluate(() => JSON.parse(sessionStorage.getItem('qa-period-snapshot')));
      const capture = async label => { assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false); await page.screenshot({ path: `${output}/${engine}-${width}-${label}.png` }); };
      const section = async (value, label) => {
        await page.locator('.accounting-toolbar').waitFor();
        const tab = page.getByRole('tab', { name: label, exact: true });
        if (await tab.isVisible()) await tab.click();
        else { const select = page.getByRole('combobox', { name: 'Section comptable', exact: true }); if (await select.isVisible() && await select.locator(`option[value=${value}]`).count()) await select.selectOption(value); else await page.getByRole('combobox', { name: 'Autres outils comptables', exact: true }).selectOption(value); }
      };
      try {
        await page.goto(`${base}/tests/mobile-harness.html?closing=1&periodGuide=1`);
        await page.getByRole('button', { name: 'Fermer le guide automatique', exact: true }).click();
        await page.getByRole('button', { name: 'Aller à un écran', exact: true }).click();
        await page.getByRole('searchbox', { name: 'Rechercher un écran' }).fill('Comptabilité');
        await page.locator('.navigation-palette__results button').filter({ has: page.getByText('Comptabilité', { exact: true }) }).click();
        await section('closing', 'Dossier de clôture');
        await page.getByRole('button', { name: 'Choisir ou créer un exercice', exact: true }).click();
        await page.getByRole('heading', { name: 'Exercices comptables', exact: true }).waitFor();
        await page.evaluate(() => window.__qaSetReadOnly(true));
        await page.waitForFunction(() => document.querySelector('.accounting-periods .section-heading button')?.disabled || [...document.querySelectorAll('button')].some(button => button.textContent.includes('Nouvel exercice') && button.disabled));
        assert.ok(await page.getByRole('button', { name: 'Nouvel exercice', exact: true }).isDisabled());
        assert.equal(await page.locator('[data-accounting-period="year-2024"]').getByRole('button', { name: 'Modifier les dates ou le nom', exact: true }).count(), 0);
        await page.evaluate(() => window.__qaSetReadOnly(false));
        await page.getByRole('button', { name: 'Nouvel exercice', exact: true }).click();
        const editor = page.locator('.accounting-period-editor');
        await editor.waitFor();
        await editor.locator('.accounting-period-editor__presets button').nth(1).click();
        const year = await page.evaluate(() => new Date().getFullYear());
        assert.equal(await editor.locator('[name=dateFrom]').inputValue(), `${year}-01-01`);
        assert.equal(await editor.locator('[name=dateTo]').inputValue(), `${year}-12-31`);
        await editor.locator('[name=name]').fill('Exercice de recette');
        await editor.locator('[name=dateFrom]').fill('2026-01-01'); await editor.locator('[name=dateTo]').fill('2026-12-31');
        const save = () => editor.getByRole('button', { name: 'Créer cet exercice', exact: true });
        await save().click();
        await editor.getByText(/Ces dates recouvrent/).waitFor();
        assert.equal((await calls('period-save')).length, 0);
        await page.waitForFunction(() => document.activeElement?.getAttribute('name') === 'dateFrom');
        await capture('overlap');
        await editor.locator('[name=dateFrom]').fill('2024-12-31'); await editor.locator('[name=dateTo]').fill('2027-12-31');
        await save().click();
        await editor.getByText(/Les comptes sont verrouillés jusqu’au/).waitFor();
        await editor.getByRole('button', { name: /^Commencer le/ }).click();
        assert.equal(await editor.locator('[name=dateFrom]').inputValue(), '2025-01-01');
        assert.equal((await calls('period-save')).length, 0);
        await editor.locator('[name=dateFrom]').fill('2027-07-01'); await editor.locator('[name=dateTo]').fill('2027-06-30');
        await save().click(); await editor.getByText(/La fin doit être le même jour/).waitFor();
        await page.waitForFunction(() => document.activeElement?.getAttribute('name') === 'dateTo');
        await editor.locator('[name=dateTo]').fill('2028-06-30');
        await flag('refuse-period'); await save().click();
        await editor.getByText('Vérifions ce point', { exact: true }).waitFor();
        assert.equal(await editor.locator('[name=name]').inputValue(), 'Exercice de recette');
        assert.equal((await snapshot()).length, 3);
        await flag('refuse-period', '0'); await flag('hold-period-save'); await flag('recover-period');
        await save().click(); await page.waitForFunction(() => sessionStorage.getItem('qa-closing-waiting-period-save') === '1');
        await editor.locator('form').evaluate(form => { form.requestSubmit(); form.requestSubmit(); });
        await page.keyboard.press('Escape'); assert.ok(await editor.isVisible());
        assert.equal((await calls('period-save')).length, 2);
        await flag('hold-period-save', '0');
        await page.getByRole('dialog', { name: 'Enregistré, affichage à actualiser', exact: true }).waitFor();
        const attempts = await calls('period-save');
        assert.equal(attempts[0].id, attempts[1].id);
        const createdId = attempts[1].id;
        assert.equal((await snapshot()).filter(period => period.id === createdId).length, 1);
        await capture('refresh-after-save');
        await page.evaluate(() => window.__qaSetReadOnly(true));
        await editor.getByRole('button', { name: 'Actualiser les données', exact: true }).click();
        assert.equal((await calls('period-save')).length, 2);
        await flag('fail-period-read', '0'); await flag('fail-refresh');
        await editor.getByRole('button', { name: 'Actualiser les données', exact: true }).click();
        await editor.getByText(/Certains états n’ont pas pu être actualisés/).waitFor();
        await flag('fail-refresh', '0'); await flag('recover-period', '0');
        await editor.getByRole('button', { name: 'Actualiser les données', exact: true }).click();
        await page.getByRole('dialog', { name: 'L’exercice est enregistré', exact: true }).waitFor();
        await editor.getByRole('button', { name: 'Ouvrir le dossier', exact: true }).click();
        assert.equal((await calls('period-save')).length, 2);
        assert.ok(await page.getByRole('button', { name: 'Préparer le contrôle', exact: true }).isDisabled());
        await expandAccountingPeriodFilters(page);
        assert.equal(await page.getByLabel('Exercice ou période comptable').inputValue(), createdId);
        assert.equal(await page.getByLabel('Date de début de la période', { exact: true }).inputValue(), '2027-07-01');
        assert.equal(await page.getByLabel('Date de fin de la période', { exact: true }).inputValue(), '2028-06-30');
        await page.evaluate(() => window.__qaSetReadOnly(false));
        await section('periods', 'Exercices');
        await page.locator(`[data-accounting-period="${createdId}"]`).getByRole('button', { name: 'Modifier les dates ou le nom', exact: true }).click();
        assert.equal(await editor.locator('[name=name]').inputValue(), 'Exercice de recette');
        await editor.locator('[name=name]').fill('Exercice corrigé'); await editor.locator('[name=dateTo]').fill('2028-05-31');
        await editor.getByRole('button', { name: 'Enregistrer les modifications', exact: true }).click();
        await page.getByRole('dialog', { name: 'L’exercice est enregistré', exact: true }).waitFor();
        await editor.getByRole('button', { name: 'Ouvrir le dossier', exact: true }).click();
        assert.equal((await snapshot()).length, 4);
        assert.equal((await calls('period-save'))[2].id, createdId);
        await expandAccountingPeriodFilters(page);
        assert.equal(await page.getByLabel('Date de fin de la période', { exact: true }).inputValue(), '2028-05-31');
        await flag('continuity-blocked');
        await page.getByRole('button', { name: 'Préparer le contrôle', exact: true }).click();
        await page.getByRole('button', { name: 'Vérifier les comptes et les opérations manquantes', exact: true }).click();
        await page.getByRole('heading', { name: 'Comptes de liaison', exact: true }).waitFor();
        await flag('continuity-blocked', '0');
        await page.getByRole('button', { name: 'Revenir au dossier de clôture', exact: true }).click();
        assert.equal(await page.locator('.closing-review-card').count(), 0);
        await page.getByRole('button', { name: 'Préparer le contrôle', exact: true }).click();
        await page.getByRole('button', { name: 'Clôturer définitivement', exact: true }).click();
        const confirmation = page.locator('.closing-confirmation');
        assert.ok((await confirmation.innerText()).includes('y compris les dates antérieures au début'));
        await confirmation.locator('input').fill('Exercice corrigé');
        await page.evaluate(() => window.__qaSetReadOnly(true));
        await page.waitForFunction(() => document.querySelector('.closing-confirmation input')?.disabled);
        assert.ok(await confirmation.getByRole('button', { name: 'Verrouiller l’exercice', exact: true }).isDisabled());
        assert.equal((await calls('finalize')).length, 0);
        await page.evaluate(() => window.__qaSetReadOnly(false));
        await capture('cumulative-confirmation');
        await flag('fail-refresh');
        await confirmation.getByRole('button', { name: 'Verrouiller l’exercice', exact: true }).click();
        await page.getByText(/La période est bien verrouillée, mais les états/).waitFor();
        assert.equal((await calls('finalize')).length, 1);
        await page.evaluate(() => window.__qaSetReadOnly(true));
        await flag('fail-refresh', '0');
        await page.getByRole('button', { name: 'Actualiser les états', exact: true }).click();
        await page.getByRole('button', { name: 'Exporter le dossier définitif', exact: true }).click();
        await page.locator('.closing-export-card').waitFor();
        assert.equal((await calls('finalize')).length, 1);
        assert.equal((await snapshot()).find(period => period.id === createdId).status, 'closed');
        await capture('final-export');
        assert.deepEqual(errors, []);
        reports.push({ engine, width, height, result: 'PASS period presets, overlap and cumulative boundary, stable id, edit, read-only recovery, current filter, closing correction navigation, cumulative confirmation, final export' });
        console.log(JSON.stringify(reports.at(-1)));
      } catch (error) { await page.screenshot({ path: `${output}/${engine}-${width}-failure.png` }); await writeFile(`${output}/${engine}-${width}-failure.txt`, await page.locator('body').innerText()); reports.push({ engine, width, error: error.stack }); throw error; }
      finally { await page.close(); }
    }
  } finally { await browser.close(); await writeFile(`${output}/report.json`, JSON.stringify(reports, null, 2)); }
}
