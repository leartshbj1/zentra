import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const { chromium } = createRequire(import.meta.url)(process.env.ZENTRA_PLAYWRIGHT_MODULE || 'playwright');
const origin = process.env.ZENTRA_QA_ORIGIN || 'http://127.0.0.1:5192';
const output = new URL('../../.qa/client-readiness-20260908/business-resolution-ui/', import.meta.url);
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true, ...(process.platform === 'win32' ? { channel: 'msedge' } : {}) });
const results = [];
const locked = page => page.locator('.desktop-app').evaluate(el => el.inert);
try {
  for (const width of [320, 390, 1440]) {
    const page = await browser.newPage({ viewport: { width, height: 1000 }, hasTouch: width < 900 });
    page.setDefaultTimeout(15000);
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    await page.goto(`${origin}/tests/mobile-harness.html?browsing=1&design=1&businessCycle=1&businessConflicts=1&businessResolution=1`);
    await page.getByRole('button', { name: 'Découvrir plus tard', exact: true }).click();
    await page.locator('.business-cycle-disclosure > summary').click();
    await page.getByRole('button', { name: 'Activer sur cet appareil', exact: true }).click();
    await page.getByRole('button', { name: 'Comparer les modifications', exact: true }).click();
    const dialog = page.getByRole('dialog', { name: 'Rapprocher les modifications', exact: true });
    await dialog.locator('.conflict-transaction').first().waitFor();
    for (const radio of await dialog.getByRole('radio', { name: /Garder la version partagée/ }).all()) await radio.check();
    await dialog.getByRole('button', { name: 'Opérations suivantes', exact: true }).click();
    await dialog.getByText('Opération 5', { exact: true }).waitFor();
    for (const radio of await dialog.getByRole('radio', { name: /Garder la version partagée/ }).all()) await radio.check();
    await dialog.getByRole('button', { name: 'Vérifier mes choix', exact: true }).click();
    await dialog.getByText(/Proposition vérifiée avec 3 documents/).waitFor();
    await dialog.getByRole('button', { name: 'Enregistrer mes choix', exact: true }).click();
    await dialog.getByRole('alert').filter({ hasText: 'Réponse interrompue' }).waitFor();
    await dialog.getByRole('button', { name: 'Vérifier mes choix', exact: true }).click();
    await dialog.getByRole('button', { name: 'Enregistrer mes choix', exact: true }).click();
    await dialog.getByRole('button', { name: 'Appliquer mes choix', exact: true }).click();
    await page.waitForFunction(() => window.__businessResolutionQa.waiting);
    assert.equal(await locked(page), true);
    await page.evaluate(() => window.__businessResolutionQa.finish());
    await page.getByText('Réponse réseau perdue. La demande reste conservée.', { exact: true }).waitFor();
    assert.equal(await locked(page), false);
    assert.equal(await page.getByRole('button', { name: 'Reprendre la résolution', exact: true }).isEnabled(), true);
    assert.equal(await page.getByRole('button', { name: 'Comparer les modifications', exact: true }).count(), 0);
    await page.screenshot({ path: fileURLToPath(new URL(`${width}-pending.png`, output)) });
    // Startup discovers durable pending state without restarting ordinary sync.
    await page.reload();
    await page.locator('.business-cycle-disclosure > summary').click();
    await page.getByRole('button', { name: 'Reprendre la résolution', exact: true }).waitFor();
    await page.evaluate(() => window.__businessResolutionQa.mode('cancel'));
    await page.getByRole('button', { name: 'Annuler la demande', exact: true }).click();
    await page.waitForFunction(() => window.__businessResolutionQa.waiting);
    assert.equal(await locked(page), true);
    await page.evaluate(() => window.__businessResolutionQa.finish());
    await page.getByText('Demande annulée. Vous pouvez comparer à nouveau les modifications.', { exact: true }).waitFor();
    assert.equal(await locked(page), false);
    await page.evaluate(() => { window.__businessResolutionQa.seed(); window.__businessResolutionQa.mode('accepted'); });
    await page.getByRole('button', { name: 'Annuler la demande', exact: true }).click();
    await page.waitForFunction(() => window.__businessResolutionQa.waiting);
    await page.evaluate(() => { window.__businessCycleQa.failNextRead(); window.__businessResolutionQa.finish(); });
    await page.getByRole('heading', { name: 'Actualisation à reprendre', exact: true }).waitFor();
    await page.screenshot({ path: fileURLToPath(new URL(`${width}-read-retry.png`, output)) });
    assert.equal(await locked(page), true);
    const writes = await page.evaluate(() => window.__businessResolutionQa.calls.filter(c => c.action !== 'permission').length);
    await page.getByRole('button', { name: 'Réessayer l’actualisation', exact: true }).click();
    await page.waitForFunction(() => !document.querySelector('.desktop-app').inert);
    assert.equal(await page.evaluate(() => window.__businessResolutionQa.calls.filter(c => c.action !== 'permission').length), writes);
    assert.ok((await page.evaluate(() => window.__businessResolutionQa.calls.filter(c => c.action === 'permission'))).every(c => c.allow && c.locked));
    const layout = await page.evaluate(() => ({ overflow: document.documentElement.scrollWidth - innerWidth,
      clipped: [...document.querySelectorAll('button')].filter(b => b.getBoundingClientRect().width && b.scrollWidth > b.clientWidth + 1).map(b => b.textContent) }));
    assert.ok(layout.overflow <= 1, JSON.stringify(layout)); assert.deepEqual(layout.clipped, []); assert.deepEqual(errors, []);
    await page.screenshot({ path: fileURLToPath(new URL(`${width}-reloaded.png`, output)), fullPage: true });
    await page.evaluate(() => window.__businessResolutionQa.seed());
    await page.goto(`${page.url()}&conflictReadOnly=1`);
    await page.locator('.business-cycle-disclosure > summary').click();
    const readonlyResume = page.getByRole('button', { name: 'Reprendre la résolution', exact: true });
    await readonlyResume.waitFor(); assert.equal(await readonlyResume.isEnabled(), false);
    assert.equal(await page.getByRole('button', { name: 'Annuler la demande', exact: true }).isEnabled(), false);
    assert.deepEqual(await page.evaluate(() => window.__businessResolutionQa.calls), []);
    results.push({ width, lostResponse: true, startupRecovery: true, cancel: true, acceptedInstallReadRetry: true, readOnlyResume: true, layout });
    await page.close();
  }
  console.log(JSON.stringify(results));
} finally { await browser.close(); }
