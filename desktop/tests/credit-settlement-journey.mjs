import { createRequire } from 'node:module';
import { mkdir, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.ZENTRA_PLAYWRIGHT_MODULE || 'playwright');
const browser = await chromium.launch({ headless: true, ...(process.platform === 'win32' ? { channel: 'msedge' } : {}) });
const report = [];
await mkdir('.qa/credit-dates', { recursive: true });
try {
  for (const width of [320, 390, 768, 1024, 1440]) {
    const page = await browser.newPage({ viewport: { width, height: 900 } });
    page.on('pageerror', (error) => report.push({ width, error: error.message }));
    await page.emulateMedia({ reducedMotion: 'reduce' });
    await page.goto('http://127.0.0.1:5175/tests/mobile-harness.html?purchasing=1&creditDates=1');
    const tour = page.getByRole('button', { name: 'Ne plus afficher automatiquement', exact: true });
    if (await tour.isVisible()) await tour.click();
    await page.getByRole('button', { name: 'Aller à un écran', exact: true }).click();
    await page.getByRole('searchbox', { name: 'Rechercher un écran' }).fill('Achats');
    await page.locator('.navigation-palette__results button').filter({ has: page.getByText('Achats & fournisseurs', { exact: true }) }).click();
    if (width <= 860) await page.getByRole('combobox', { name: 'Section des achats', exact: true }).selectOption('documents');
    else await page.locator('#purchase-tab-documents').click();
    const card = (reference) => page.locator('.purchase-document-card--credit').filter({ has: page.getByRole('heading', { name: reference, exact: true }) });
    const dialog = page.getByRole('dialog');
    const capture = async (name) => {
      const geometry = await page.evaluate(() => ({ viewport: innerWidth, document: document.documentElement.scrollWidth, invalidControls: [...document.querySelectorAll('[role="dialog"] input, [role="dialog"] select, [role="dialog"] textarea')].filter((element) => { const r = element.getBoundingClientRect(); return r.width && (r.left < -1 || r.right > innerWidth + 1); }).map((element) => element.outerHTML.slice(0, 160)) }));
      assert.ok(geometry.document <= width + 1, `${name} has horizontal overflow`);
      assert.deepEqual(geometry.invalidControls, [], `${name} clips controls`);
      await page.screenshot({ path: `.qa/credit-dates/${width}-${name}.png` });
    };
    await card('AV-DRAFT-DATES').getByRole('button', { name: 'Contrôler et valider', exact: true }).click();
    assert.equal(await dialog.getByRole('button', { name: 'Valider et comptabiliser', exact: true }).isDisabled(), true);
    await dialog.getByText('Date de compensation à renseigner', { exact: true }).waitFor();
    await capture('legacy-guard');
    await dialog.getByRole('button', { name: 'Retour au brouillon', exact: true }).click();
    await card('AV-DRAFT-DATES').getByRole('button', { name: 'Modifier', exact: true }).click();
    const date = dialog.getByLabel(/^Date de compensation ·/);
    assert.equal(await date.inputValue(), '', 'an old timestamp is not silently converted to a settlement date');
    assert.equal(await dialog.getByText('NE-PAS-PROPOSER-EUR', { exact: true }).count(), 0);
    assert.equal(await dialog.getByText('NE-PAS-PROPOSER-AUTRE-FOURNISSEUR', { exact: true }).count(), 0);
    await date.fill('2026-09-03');
    await date.scrollIntoViewIfNeeded();
    await capture('draft-date');
    await dialog.getByRole('button', { name: 'Enregistrer le brouillon', exact: true }).click();
    await dialog.waitFor({ state: 'detached' });
    const saved = await page.evaluate(() => JSON.parse(sessionStorage.getItem('qa-credit-date-save')));
    assert.equal(saved[0].allocations[0].effectiveDate, '2026-09-03');
    await card('AV-DRAFT-DATES').getByRole('button', { name: 'Contrôler et valider', exact: true }).click();
    await dialog.getByText(/^Compensation le 03 sept.*2026$/).waitFor();
    assert.equal(await dialog.getByRole('button', { name: 'Valider et comptabiliser', exact: true }).isEnabled(), true);
    await capture('dated-preview');
    await dialog.getByRole('button', { name: 'Valider et comptabiliser', exact: true }).click();
    await dialog.waitFor({ state: 'detached' });
    await card('AV-AVAILABLE').getByRole('button', { name: 'Imputer sur une facture', exact: true }).click();
    assert.equal(await dialog.getByRole('option', { name: /NE-PAS-PROPOSER/ }).count(), 0);
    const applicationDate = dialog.getByLabel(/^Date de compensation/);
    await applicationDate.fill('2026-09-01');
    assert.equal(await dialog.getByRole('button', { name: 'Confirmer l’imputation', exact: true }).isDisabled(), true);
    await applicationDate.fill('2099-01-01');
    assert.equal(await dialog.getByRole('button', { name: 'Confirmer l’imputation', exact: true }).isDisabled(), true);
    await applicationDate.fill('2026-09-03');
    await dialog.getByRole('spinbutton', { name: /^Montant imputé/ }).fill('9');
    await page.evaluate(() => sessionStorage.setItem('qa-credit-date-reject', '1'));
    await dialog.getByRole('button', { name: 'Confirmer l’imputation', exact: true }).click();
    await dialog.getByRole('alert').filter({ hasText: 'La période comptable est clôturée' }).waitFor();
    assert.equal(await applicationDate.inputValue(), '2026-09-03');
    assert.equal(await dialog.getByRole('spinbutton', { name: /^Montant imputé/ }).inputValue(), '9');
    await capture('native-refusal');
    await dialog.getByRole('button', { name: 'Confirmer l’imputation', exact: true }).click();
    await dialog.waitFor({ state: 'detached' });
    const applications = await page.evaluate(() => JSON.parse(sessionStorage.getItem('qa-credit-date-apply')));
    assert.equal(applications.length, 2);
    assert.deepEqual(applications[0], applications[1], 'same dated intent is retained on retry');
    assert.equal(applications[0].amountCents, 900);
    await card('AV-AVAILABLE').getByRole('button', { name: 'Extourner', exact: true }).click();
    await dialog.getByRole('textbox', { name: /^Motif de l’extourne/ }).fill('Mauvaise facture sélectionnée');
    await dialog.getByLabel(/^Date de l’extourne/).fill('2026-09-02');
    assert.equal(await dialog.getByRole('button', { name: 'Confirmer l’extourne', exact: true }).isDisabled(), true);
    await dialog.getByLabel(/^Date de l’extourne/).fill('2026-09-04');
    await capture('reversal');
    await dialog.getByRole('button', { name: 'Confirmer l’extourne', exact: true }).click();
    await dialog.waitFor({ state: 'detached' });
    const reversals = await page.evaluate(() => JSON.parse(sessionStorage.getItem('qa-credit-date-reverse')));
    assert.equal(reversals.length, 1);
    assert.equal(reversals[0].effectiveDate, '2026-09-04');
    assert.equal(await card('AV-AVAILABLE').getByRole('button', { name: 'Extourner', exact: true }).count(), 0);
    await card('AV-AVAILABLE').locator('summary').click();
    const history = card('AV-AVAILABLE').locator('.credit-application-history li');
    assert.equal(await history.count(), 2);
    assert.match(await history.nth(0).innerText(), /Extourne.*9\.00\sCHF/s);
    assert.match(await history.nth(0).innerText(), /04 sept.*2026/);
    assert.match(await history.nth(0).innerText(), /Mauvaise facture sélectionnée/);
    assert.match(await history.nth(1).innerText(), /Compensation.*9\.00\sCHF/s);
    assert.match(await history.nth(1).innerText(), /03 sept.*2026/);
    await history.nth(0).scrollIntoViewIfNeeded();
    await capture('restored-balance');
    report.push({ width, result: 'PASS legacy date recovery, draft validation, native refusal preserved, dated retry and reversal', captures: 6 });
    await page.close();
  }
  assert.deepEqual(report.filter((entry) => entry.error), []);
} catch (error) { report.push({ fatal: error.stack }); process.exitCode = 1; }
finally { await writeFile('.qa/credit-dates/report.json', JSON.stringify(report, null, 2)); console.log(JSON.stringify(report, null, 2)); await browser.close(); }
