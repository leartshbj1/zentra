const MAX_FILE_BYTES: u64 = 2 * 1024 * 1024;
const MAX_FILES: usize = 3;
const MAX_BATCH_EVENTS: usize = 100;
const MAX_DURATION_MS: u64 = 86_400_000;
const MAX_SLUG_BYTES: usize = 80;
const ERROR_CODES: &[&str] = &[
    "NETWORK",
    "SESSION",
    "PERMISSION",
    "CONFLICT",
    "VALIDATION",
    "STORAGE",
    "NOT_FOUND",
    "INTERNAL",
    "UNHANDLED",
    "RENDER",
    "LOG_WRITE_FAILED",
    "storage.database",
    "storage.io",
    "input.json",
    "document.pdf",
    "import.archive",
    "input.validation",
    "service.remote",
    "record.not_found",
    "setup.required",
    "storage.unsafe_path",
    "platform.unsupported",
];
const FILE_NAMES: [&str; MAX_FILES] = ["events.jsonl", "events.1.jsonl", "events.2.jsonl"];
static ACTIVE_LOG: OnceLock<Mutex<Option<DiagnosticLog>>> = OnceLock::new();

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum DiagnosticArea {
    App,
    Command,
    Navigation,
    Sync,
    Draft,
    Error,
    Export,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum DiagnosticPhase {
    Start,
    Success,
    Failure,
    Info,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct DiagnosticEvent {
    id: String,
    session_id: String,
    timestamp: String,
    area: DiagnosticArea,
    operation: String,
    phase: DiagnosticPhase,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    duration_ms: Option<u64>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    error_code: Option<String>,
}

// Application metadata is generated by the native build, never accepted from
// an IPC payload. Explicit nesting also avoids flatten/deny_unknown_fields.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
struct DiagnosticRecord {
    event: DiagnosticEvent,
    app_version: String,
    platform: String,
}

#[derive(Debug, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct DiagnosticsSummary {
    session_id: String,
    app_version: String,
    platform: String,
    event_count: usize,
    file_count: usize,
    size_bytes: u64,
    max_file_bytes: u64,
    max_files: usize,
    first_event_at: Option<String>,
    last_event_at: Option<String>,
    last_incident: Option<DiagnosticEvent>,
}

#[derive(Clone)]
pub struct DiagnosticLog(Arc<LogInner>);

/// Closed startup phases: callers cannot supply paths or exception text.
#[derive(Clone, Copy)]
pub(crate) enum StartupOperation {
    Updater,
    LocalStore,
}

struct LogInner {
    data_dir: PathBuf,
    directory: PathBuf,
    exports_dir: PathBuf,
    session_id: String,
    app_version: String,
    platform: String,
    max_file_bytes: u64,
    operation_lock: Mutex<()>,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, thiserror::Error)]
enum DiagnosticError {
    #[error("Les informations du journal technique sont invalides.")]
    InvalidEvent,
    #[error("Le journal technique accepte au maximum 100 évènements à la fois.")]
    BatchTooLarge,
    #[error("Le journal technique est momentanément indisponible.")]
    StorageUnavailable,
}

fn storage_error<T>(_: T) -> DiagnosticError {
    DiagnosticError::StorageUnavailable
}

fn valid_slug(value: &str) -> bool {
    !value.is_empty()
        && value.len() <= MAX_SLUG_BYTES
        && value
            .bytes()
            .all(|byte| byte.is_ascii_alphanumeric() || matches!(byte, b'_' | b'.' | b'-'))
}

impl DiagnosticEvent {
    fn validate(&self) -> Result<(), DiagnosticError> {
        if self.id.len() != 36
            || self.session_id.len() != 36
            || Uuid::parse_str(&self.id).is_err()
            || Uuid::parse_str(&self.session_id).is_err()
            || self.timestamp.len() > 40
            || DateTime::parse_from_rfc3339(&self.timestamp).is_err()
            || !valid_slug(&self.operation)
            || self
                .duration_ms
                .is_some_and(|value| value > MAX_DURATION_MS)
            || self
                .error_code
                .as_deref()
                .is_some_and(|code| !ERROR_CODES.contains(&code))
        {
            return Err(DiagnosticError::InvalidEvent);
        }
        Ok(())
    }

    fn native(
        session_id: &str,
        operation: &str,
        phase: DiagnosticPhase,
        code: Option<&str>,
    ) -> Self {
        Self {
            id: Uuid::new_v4().to_string(),
            session_id: session_id.into(),
            timestamp: Utc::now().to_rfc3339_opts(SecondsFormat::Millis, true),
            area: if code.is_some() {
                DiagnosticArea::Command
            } else {
                DiagnosticArea::App
            },
            operation: operation.into(),
            phase,
            duration_ms: None,
            error_code: code.map(str::to_owned),
        }
    }
}

/// Initialization is deliberately best effort: an unwritable diagnostic folder
/// must never stop a company from opening. Commands report a fixed error later.
pub fn initialize(data_dir: &Path) -> DiagnosticLog {
    let log = DiagnosticLog::new(data_dir, MAX_FILE_BYTES);
    if let Ok(mut active) = ACTIVE_LOG.get_or_init(|| Mutex::new(None)).lock() {
        *active = Some(log.clone());
    }
    let _ = log.append(&[DiagnosticEvent::native(
        &log.0.session_id,
        "app.start",
        DiagnosticPhase::Info,
        None,
    )]);
    log
}

impl DiagnosticLog {
    fn new(data_dir: &Path, max_file_bytes: u64) -> Self {
        Self(Arc::new(LogInner {
            data_dir: data_dir.to_owned(),
            directory: data_dir.join("diagnostics"),
            exports_dir: data_dir.join("exports"),
            session_id: Uuid::new_v4().to_string(),
            app_version: env!("CARGO_PKG_VERSION").into(),
            platform: std::env::consts::OS.into(),
            max_file_bytes,
            operation_lock: Mutex::new(()),
        }))
    }

    fn ensure_directory(&self, directory: &Path) -> Result<(), DiagnosticError> {
        // The chosen profile root has already been created. A fixed child path
        // must not be redirected by a symbolic link into another directory.
        match fs::symlink_metadata(directory) {
            Ok(metadata) if metadata.file_type().is_symlink() || !metadata.is_dir() => {
                return Err(DiagnosticError::StorageUnavailable);
            }
            Ok(_) => {}
            Err(error) if error.kind() == ErrorKind::NotFound => {
                fs::create_dir_all(directory).map_err(storage_error)?;
            }
            Err(error) => return Err(storage_error(error)),
        }
        let root = self.0.data_dir.canonicalize().map_err(storage_error)?;
        let canonical = directory.canonicalize().map_err(storage_error)?;
        if canonical == root || !canonical.starts_with(&root) {
            return Err(DiagnosticError::StorageUnavailable);
        }
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            fs::set_permissions(directory, fs::Permissions::from_mode(0o700))
                .map_err(storage_error)?;
        }
        Ok(())
    }

    fn file_size(&self, path: &Path) -> Result<Option<u64>, DiagnosticError> {
        match fs::symlink_metadata(path) {
            Ok(metadata) if metadata.file_type().is_symlink() || !metadata.is_file() => {
                Err(DiagnosticError::StorageUnavailable)
            }
            Ok(metadata) if metadata.len() > self.0.max_file_bytes => {
                Err(DiagnosticError::StorageUnavailable)
            }
            Ok(metadata) => Ok(Some(metadata.len())),
            Err(error) if error.kind() == ErrorKind::NotFound => Ok(None),
            Err(error) => Err(storage_error(error)),
        }
    }

    fn rotate(&self) -> Result<(), DiagnosticError> {
        let oldest = self.0.directory.join(FILE_NAMES[2]);
        if self.file_size(&oldest)?.is_some() {
            fs::remove_file(&oldest).map_err(storage_error)?;
        }
        for index in (0..MAX_FILES - 1).rev() {
            let source = self.0.directory.join(FILE_NAMES[index]);
            if self.file_size(&source)?.is_some() {
                fs::rename(source, self.0.directory.join(FILE_NAMES[index + 1]))
                    .map_err(storage_error)?;
            }
        }
        Ok(())
    }

    fn append(&self, events: &[DiagnosticEvent]) -> Result<(), DiagnosticError> {
        if events.len() > MAX_BATCH_EVENTS {
            return Err(DiagnosticError::BatchTooLarge);
        }
        // Validate the complete batch before any event can reach the journal.
        for event in events {
            event.validate()?;
        }
        if events.is_empty() {
            return Ok(());
        }
        let lines = events
            .iter()
            .map(|event| {
                let record = DiagnosticRecord {
                    event: event.clone(),
                    app_version: self.0.app_version.clone(),
                    platform: self.0.platform.clone(),
                };
                let mut line = serde_json::to_vec(&record).map_err(storage_error)?;
                line.push(b'\n');
                if line.len() as u64 > self.0.max_file_bytes {
                    return Err(DiagnosticError::InvalidEvent);
                }
                Ok(line)
            })
            .collect::<Result<Vec<_>, DiagnosticError>>()?;
        let _guard = self.0.operation_lock.lock().map_err(storage_error)?;
        self.ensure_directory(&self.0.directory)?;
        let current = self.0.directory.join(FILE_NAMES[0]);
        let mut size = self.file_size(&current)?.unwrap_or(0);
        let mut open_file: Option<fs::File> = None;
        for line in lines {
            if size + line.len() as u64 > self.0.max_file_bytes {
                // Windows cannot rename an open file. Close before rotation,
                // otherwise reuse the same handle for the complete batch.
                if let Some(mut file) = open_file.take() {
                    file.flush().map_err(storage_error)?;
                }
                self.rotate()?;
                size = 0;
            }
            if open_file.is_none() {
                let mut options = OpenOptions::new();
                options.create(true).append(true);
                #[cfg(unix)]
                {
                    use std::os::unix::fs::OpenOptionsExt;
                    options.mode(0o600);
                }
                open_file = Some(options.open(&current).map_err(storage_error)?);
            }
            open_file
                .as_mut()
                .ok_or(DiagnosticError::StorageUnavailable)?
                .write_all(&line)
                .map_err(storage_error)?;
            size += line.len() as u64;
        }
        if let Some(mut file) = open_file {
            file.flush().map_err(storage_error)?;
        }
        Ok(())
    }

    fn records(&self) -> Result<(Vec<DiagnosticRecord>, usize, u64), DiagnosticError> {
        self.ensure_directory(&self.0.directory)?;
        let mut records = Vec::new();
        let mut files = 0;
        let mut bytes = 0;
        for name in FILE_NAMES.iter().rev() {
            let path = self.0.directory.join(name);
            if let Some(size) = self.file_size(&path)? {
                files += 1;
                bytes += size;
                let mut text = String::new();
                fs::File::open(path)
                    .map_err(storage_error)?
                    .take(self.0.max_file_bytes + 1)
                    .read_to_string(&mut text)
                    .map_err(storage_error)?;
                if text.len() as u64 > self.0.max_file_bytes {
                    return Err(DiagnosticError::StorageUnavailable);
                }
                for line in text.lines() {
                    // Partial writes or manually altered files never turn
                    // into arbitrary data in an export or an error message.
                    if let Ok(record) = serde_json::from_str::<DiagnosticRecord>(line) {
                        if record.event.validate().is_ok()
                            && !record.app_version.is_empty()
                            && record.app_version.len() <= 30
                            && record
                                .app_version
                                .bytes()
                                .all(|byte| byte.is_ascii_digit() || byte == b'.')
                            && ["windows", "macos", "linux", "android", "ios"]
                                .contains(&record.platform.as_str())
                        {
                            records.push(record);
                        }
                    }
                }
            }
        }
        Ok((records, files, bytes))
    }

    fn summary(&self) -> Result<DiagnosticsSummary, DiagnosticError> {
        let _guard = self.0.operation_lock.lock().map_err(storage_error)?;
        let (records, file_count, size_bytes) = self.records()?;
        let mut first_event: Option<(DateTime<chrono::FixedOffset>, usize)> = None;
        let mut last_event: Option<(DateTime<chrono::FixedOffset>, usize)> = None;
        let mut last_failure: Option<(DateTime<chrono::FixedOffset>, usize)> = None;
        for (index, record) in records.iter().enumerate() {
            // A frontend batch can arrive after a newer native event. Compare
            // real instants, retaining the original timestamp/reference. For
            // equal instants the first/last physical record is deterministic.
            let timestamp = DateTime::parse_from_rfc3339(&record.event.timestamp)
                .map_err(|_| DiagnosticError::InvalidEvent)?;
            let key = (timestamp, index);
            if first_event.as_ref().is_none_or(|current| &key < current) {
                first_event = Some(key.clone());
            }
            if last_event.as_ref().is_none_or(|current| &key > current) {
                last_event = Some(key.clone());
            }
            if record.event.phase == DiagnosticPhase::Failure
                && last_failure.as_ref().is_none_or(|current| &key > current)
            {
                last_failure = Some(key);
            }
        }
        let first_event_at = first_event.map(|(_, index)| records[index].event.timestamp.clone());
        let last_event_at = last_event.map(|(_, index)| records[index].event.timestamp.clone());
        let last_incident = last_failure.map(|(_, index)| records[index].event.clone());
        Ok(DiagnosticsSummary {
            session_id: self.0.session_id.clone(),
            app_version: self.0.app_version.clone(),
            platform: self.0.platform.clone(),
            event_count: records.len(),
            file_count,
            size_bytes,
            max_file_bytes: self.0.max_file_bytes,
            max_files: MAX_FILES,
            first_event_at,
            last_event_at,
            last_incident,
        })
    }

    fn export(&self) -> Result<PathBuf, DiagnosticError> {
        let _guard = self.0.operation_lock.lock().map_err(storage_error)?;
        let (records, _, _) = self.records()?;
        self.ensure_directory(&self.0.exports_dir)?;
        let directory = self
            .0
            .exports_dir
            .join(format!("diagnostics-{}", Uuid::new_v4()));
        self.ensure_directory(&directory)?;
        let path = directory.join("Zentra-diagnostics.jsonl");
        let mut options = OpenOptions::new();
        options.create_new(true).write(true);
        #[cfg(unix)]
        {
            use std::os::unix::fs::OpenOptionsExt;
            options.mode(0o600);
        }
        let mut file = options.open(&path).map_err(storage_error)?;
        for record in records {
            serde_json::to_writer(&mut file, &record).map_err(storage_error)?;
            file.write_all(b"\n").map_err(storage_error)?;
        }
        file.flush().map_err(storage_error)?;
        Ok(path)
    }

    fn clear(&self) -> Result<(), DiagnosticError> {
        let _guard = self.0.operation_lock.lock().map_err(storage_error)?;
        self.ensure_directory(&self.0.directory)?;
        for name in FILE_NAMES {
            let path = self.0.directory.join(name);
            // Clearing must also recover a journal altered beyond its byte
            // limit. Fixed regular files may be removed without reading them.
            match fs::symlink_metadata(&path) {
                Ok(metadata) if metadata.file_type().is_symlink() || !metadata.is_file() => {
                    return Err(DiagnosticError::StorageUnavailable);
                }
                Ok(_) => fs::remove_file(path).map_err(storage_error)?,
                Err(error) if error.kind() == ErrorKind::NotFound => {}
                Err(error) => return Err(storage_error(error)),
            }
        }
        Ok(())
    }

    fn append_native_error(&self, error: &AppError) {
        self.append_native_failure(DiagnosticArea::Command, "command.native", error);
    }

    pub(crate) fn record_startup_failure(&self, operation: StartupOperation) {
        let (operation, code) = match operation {
            StartupOperation::Updater => ("app.updater.initialize", "INTERNAL"),
            StartupOperation::LocalStore => ("app.local_store.initialize", "STORAGE"),
        };
        let mut event = DiagnosticEvent::native(
            &self.0.session_id,
            operation,
            DiagnosticPhase::Failure,
            Some(code),
        );
        event.area = DiagnosticArea::App;
        // The original startup error is never replaced by a journal failure.
        let _ = self.append(&[event]);
    }

    fn append_project_exchange_failure(&self, error: &AppError) {
        self.append_native_failure(DiagnosticArea::Sync, "project.exchange", error);
    }

    fn append_attachment_cleanup_failure(&self, error: &AppError) {
        self.append_native_failure(DiagnosticArea::Command, "attachment.cleanup_failure", error);
    }

    fn append_native_failure(&self, area: DiagnosticArea, operation: &'static str, error: &AppError) {
        let mut event = DiagnosticEvent::native(
            &self.0.session_id,
            operation,
            DiagnosticPhase::Failure,
            Some(native_error_code(error)),
        );
        event.area = area;
        let _ = self.append(&[event]);
    }
}

fn native_error_code(error: &AppError) -> &'static str {
    match error {
        AppError::Database(_) => "storage.database",
        AppError::Io(_) => "storage.io",
        AppError::Json(_) => "input.json",
        AppError::Pdf(_) => "document.pdf",
        AppError::Archive(_) => "import.archive",
        AppError::Validation(_) => "input.validation",
        AppError::Remote(_) => "service.remote",
        AppError::NotFound(_) => "record.not_found",
        AppError::OnboardingRequired => "setup.required",
        AppError::UnsafePath(_) => "storage.unsafe_path",
        AppError::UnsupportedPlatform => "platform.unsupported",
    }
}

/// Called before formatting a native command error. Formatting remains unchanged
/// for users; only the static category above is permitted in the technical log.
pub(crate) fn record_native_error(error: &AppError) {
    let active = ACTIVE_LOG.get().and_then(|slot| slot.lock().ok()?.clone());
    if let Some(log) = active {
        log.append_native_error(error);
    }
}

pub(crate) struct PreparedNativeError {
    log: DiagnosticLog,
    event: DiagnosticEvent,
}

/// Capture the failure instant and a closed category before waiting for I/O.
/// This owned receipt deliberately retains no exception or business payload.
pub(crate) fn prepare_native_error(error: &AppError) -> Option<PreparedNativeError> {
    let log = ACTIVE_LOG.get().and_then(|slot| slot.lock().ok()?.clone())?;
    let event = DiagnosticEvent::native(
        &log.0.session_id,
        "command.native",
        DiagnosticPhase::Failure,
        Some(native_error_code(error)),
    );
    Some(PreparedNativeError { log, event })
}

pub(crate) async fn record_prepared_native_error(prepared: Option<PreparedNativeError>) {
    if let Some(PreparedNativeError { log, event }) = prepared {
        // Await the best-effort journal receipt, without detaching a task or
        // keeping the account lock while the log/export mutex is occupied.
        let _ = tauri::async_runtime::spawn_blocking(move || log.append(&[event])).await;
    }
}

/// A failed exchange remains an Ok status for the scheduler. Record only its
/// static technical category, never the status message or document metadata.
pub(crate) fn record_project_exchange_failure(error: &AppError) {
    let active = ACTIVE_LOG.get().and_then(|slot| slot.lock().ok()?.clone());
    if let Some(log) = active {
        log.append_project_exchange_failure(error);
    }
}

/// The document deletion is committed. Report physical cleanup separately,
/// without storing a path, attachment identity, file hash or raw error text.
pub(crate) fn record_attachment_cleanup_failure(error: &AppError) {
    let active = ACTIVE_LOG.get().and_then(|slot| slot.lock().ok()?.clone());
    if let Some(log) = active {
        log.append_attachment_cleanup_failure(error);
    }
}

#[tauri::command]
pub async fn append_diagnostic_events(
    state: State<'_, DiagnosticLog>,
    events: Vec<DiagnosticEvent>,
) -> Result<(), String> {
    let log = state.inner().clone();
    tauri::async_runtime::spawn_blocking(move || log.append(&events))
        .await
        .map_err(|_| DiagnosticError::StorageUnavailable.to_string())?
        .map_err(|error| error.to_string())
}

#[tauri::command]
pub async fn get_diagnostics_summary(
    state: State<'_, DiagnosticLog>,
) -> Result<DiagnosticsSummary, String> {
    let log = state.inner().clone();
    tauri::async_runtime::spawn_blocking(move || log.summary())
        .await
        .map_err(|_| DiagnosticError::StorageUnavailable.to_string())?
        .map_err(|error| error.to_string())
}

#[tauri::command]
pub async fn export_diagnostics(state: State<'_, DiagnosticLog>) -> Result<String, String> {
    let log = state.inner().clone();
    tauri::async_runtime::spawn_blocking(move || log.export())
        .await
        .map_err(|_| DiagnosticError::StorageUnavailable.to_string())?
        .map(|path| path.to_string_lossy().into_owned())
        .map_err(|error| error.to_string())
}

