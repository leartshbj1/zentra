    #[test]
    fn native_errors_never_log_exception_text_or_paths() {
        let (_temporary, log) = fixture(MAX_FILE_BYTES);
        let errors = [
            AppError::Remote("Bearer private-secret-token mail@example.ch".into()),
            AppError::Validation("Invoice body and private password".into()),
            AppError::UnsafePath(PathBuf::from("/private/company-document.pdf")),
        ];
        for error in &errors {
            log.append_native_error(error);
        }
        let text = fs::read_to_string(log.export().unwrap()).unwrap();
        for secret in [
            "Bearer",
            "private-secret-token",
            "mail@example.ch",
            "Invoice body",
            "private password",
            "company-document.pdf",
        ] {
            assert!(!text.contains(secret));
        }
        let summary = log.summary().unwrap();
        assert_eq!(summary.event_count, 3);
        assert_eq!(
            summary.last_incident.unwrap().error_code.as_deref(),
            Some("storage.unsafe_path")
        );
    }

    #[test]
    fn committed_attachment_cleanup_failure_logs_only_static_operation_and_category() {
        let (_temporary, log) = fixture(MAX_FILE_BYTES);
        let error = AppError::Io(std::io::Error::new(
            std::io::ErrorKind::PermissionDenied,
            "private/company-invoice.pdf sha256=private-hash id=private-attachment",
        ));
        log.append_attachment_cleanup_failure(&error);
        let (records, _, _) = log.records().unwrap();
        assert_eq!(records.len(), 1);
        assert_eq!(records[0].event.operation, "attachment.cleanup_failure");
        assert_eq!(records[0].event.phase, DiagnosticPhase::Failure);
        assert_eq!(records[0].event.error_code.as_deref(), Some("storage.io"));
        let text = fs::read_to_string(log.export().unwrap()).unwrap();
        for secret in [
            "company-invoice.pdf",
            "private-hash",
            "private-attachment",
            &error.to_string(),
        ] {
            assert!(!text.contains(secret));
        }
        // An unwritable diagnostic path remains best effort and cannot turn
        // this already-committed business outcome into a new command failure.
        log.clear().unwrap();
        fs::remove_dir(&log.0.directory).unwrap();
        fs::write(&log.0.directory, b"synthetic blocked journal").unwrap();
        log.append_attachment_cleanup_failure(&error);
    }

    #[test]
    fn failed_project_exchange_keeps_status_contract_and_logs_only_its_category() {
        let (_temporary, log) = fixture(MAX_FILE_BYTES);
        let connection = Connection::open_in_memory().unwrap();
        let database_error = connection
            .query_row("SELECT * FROM \"private-secret-token\"", [], |_| Ok(()))
            .unwrap_err();
        let error = AppError::Database(database_error);
        let expected_message = error.to_string();
        let status = crate::project_sync::project_exchange_status(
            serde_json::json!({"pending":2,"documents":[],"syncing":true}),
            Err(error),
            |error| log.append_project_exchange_failure(error),
        );
        assert_eq!(status["error"], expected_message);
        assert_eq!(status["changed"], true);
        assert_eq!(status["syncing"], false);
        assert_eq!(status["pending"], 2);
        let (records, _, _) = log.records().unwrap();
        assert_eq!(records.len(), 1);
        let event = &records[0].event;
        assert_eq!(event.area, DiagnosticArea::Sync);
        assert_eq!(event.operation, "project.exchange");
        assert_eq!(event.phase, DiagnosticPhase::Failure);
        assert_eq!(event.error_code.as_deref(), Some("storage.database"));
        let text = fs::read_to_string(log.export().unwrap()).unwrap();
        assert!(!text.contains("private-secret-token"));
        assert!(!text.contains(&expected_message));
    }

