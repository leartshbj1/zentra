export const phase2ArchiveDeleteGuard="CREATE TRIGGER invoice_archives_immutable_delete_guard\nBEFORE DELETE ON invoice_archives\nWHEN OLD.storage_status<>'pending'\nBEGIN SELECT RAISE(ABORT,'invoice archives cannot be deleted'); END";

export function phase2ResetStatements(counts:Record<string,number>):string[] {
  const guards=Object.entries(counts).map(([name,count])=>`(SELECT COUNT(*) FROM "${name}")=${count}`);
  return [
    'CREATE TABLE _phase2_reset_guard (ok INTEGER NOT NULL CHECK(ok=1))',
    ...Array.from({length:Math.ceil(guards.length/20)},(_,i)=>`INSERT INTO _phase2_reset_guard(ok) SELECT CASE WHEN ${guards.slice(i*20,i*20+20).join(' AND ')} THEN 1 ELSE 0 END`),
    'DROP TRIGGER invoice_archives_immutable_delete_guard',
    ...phase2DeleteOrder.filter(t=>counts[t]>0).map(t=>`DELETE FROM "${t}"`),
    phase2ArchiveDeleteGuard,
    'DROP TABLE _phase2_reset_guard',
  ];
}
